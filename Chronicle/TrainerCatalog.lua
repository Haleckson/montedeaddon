C.TrainerCatalog = data

local cachedClass, cachedRace, cachedEntries
local function normalizedRace(value)
    return type(value) == "string" and value:lower():gsub("[^%a]", "") or ""
end

function C:GetTrainerCatalogEntries()
    if not UnitClass then return {} end
    local _, class = UnitClass("player")
    local race = UnitRace and select(2, UnitRace("player"))
    if not class or not data[class] then return {} end
    if cachedEntries and cachedClass == class and cachedRace == race then return cachedEntries end
    local entries = {}
    local rankWord = GetLocale and GetLocale() == "deDE" and "Rang " or "Rank "
    for _, record in ipairs(data[class]) do
        local id, level, rankNumber, englishName, iconName, races =
            record[1], record[2], record[3], record[4], record[5], record[6]
        local allowed = races == ""
        for candidate in races:gmatch("[^,]+") do
            if normalizedRace(candidate) == normalizedRace(race) then allowed = true end
        end
        if allowed then
            local name, icon
            if C_Spell and C_Spell.GetSpellInfo then
                local ok, info = pcall(C_Spell.GetSpellInfo, id)
                if ok and type(info) == "table" then name, icon = info.name, info.iconID end
            end
            if not name and GetSpellInfo then
                local ok, spellName, _, spellIcon = pcall(GetSpellInfo, id)
                if ok then name, icon = spellName, spellIcon end
            end
            local rank = rankNumber > 0 and (rankWord .. rankNumber) or nil
            entries[#entries + 1] = {
                spellID = id, level = level, name = name or englishName, rank = rank,
                icon = icon or (iconName ~= "" and "Interface\\Icons\\" .. iconName or nil),
                source = "catalog",
            }
        end
    end
    cachedClass, cachedRace, cachedEntries = class, race, entries
    return entries
end
