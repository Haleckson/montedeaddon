local aliases = { ["Hall of Thanes"] = "The Hall of Thanes",
    ["Ahn'Qiraj Temple"] = "Temple of Ahn'Qiraj",
    ["Stormwind Stockade"] = "The Stockade" }
function C:GetBossMetadata(instanceName, bossName, npcID)
    local bosses = self.bossMetadata[aliases[instanceName] or instanceName]
    if not bosses then return nil end
    if bossName and bosses[bossName] then return bosses[bossName] end
    if npcID then
        for _, metadata in pairs(bosses) do
            if metadata[3] == npcID then return metadata end
        end
    end
    return nil
end
