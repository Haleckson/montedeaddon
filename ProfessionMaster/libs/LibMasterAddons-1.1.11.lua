--[[

LibMasterAddons-1.0 — log service

Persistent day-keyed log in the addon's <storagePrefix>_Logs SavedVariable
(entries older than 7 days are purged on start, each day is capped so the
saved variables stay small). Used by addon:Log(...).

@author Kurki
@copyright ©2026 LibMasterAddons. All Rights Reserved.

--]]

local Lib = LibStub:GetLibrary("LibMasterAddons-1.0", true);
if (not Lib or not Lib.isLoading) then
    return;
end

-- define built-in service
local LogService = Lib:DefineService("log");

--- Initialize service.
function LogService:Initialize()
    -- purge entries older than 7 days
    self.RetentionDays = 7;

    -- cap per day so a runaway logger cannot blow up the saved variables
    self.MaxDayEntries = 500;

    self:PurgeOldEntries();
end

--- Get the log storage table (<storagePrefix>_Logs).
-- @return Day-keyed log table.
function LogService:GetLogs()
    return self.addon:GetSavedTable("Logs");
end

--- Log a message.
-- @param ... The values to log (concatenated with spaces).
function LogService:AddEntry(...)
    local parts = {};
    for index = 1, select("#", ...) do
        local value = select(index, ...);
        table.insert(parts, tostring(value));
    end

    local message = table.concat(parts, " ");
    local dayKey = date("%Y-%m-%d");
    local logs = self:GetLogs();

    -- ensure day array exists
    if (not logs[dayKey]) then
        logs[dayKey] = {};
    end
    local dayEntries = logs[dayKey];

    -- stop at the day cap with a single marker entry (fallback covers calls
    -- before Initialize ran)
    local maxDayEntries = self.MaxDayEntries or 500;
    if (#dayEntries >= maxDayEntries) then
        if (#dayEntries == maxDayEntries) then
            table.insert(dayEntries, date("%H:%M:%S") .. " Log limit for this day reached, further entries are dropped.");
        end
        return;
    end

    table.insert(dayEntries, date("%H:%M:%S") .. " " .. message);
end

--- Purge log entries older than the retention period.
function LogService:PurgeOldEntries()
    local logs = self:GetLogs();
    local cutoff = time() - self.RetentionDays * 24 * 60 * 60;
    local maxDayEntries = self.MaxDayEntries or 500;
    for dayKey, dayEntries in pairs(logs) do
        -- parse day key
        local year, month, day = tostring(dayKey):match("^(%d+)-(%d+)-(%d+)$");
        if (year) then
            local entryTime = time({ year = tonumber(year), month = tonumber(month), day = tonumber(day) });
            if (entryTime < cutoff) then
                logs[dayKey] = nil;
            elseif (#dayEntries > maxDayEntries + 1) then
                -- trim days written by versions without a cap
                for index = #dayEntries, maxDayEntries + 2, -1 do
                    dayEntries[index] = nil;
                end
                dayEntries[maxDayEntries + 1] = "Log limit for this day reached, further entries were dropped.";
            end
        else
            -- legacy flat entry, remove
            logs[dayKey] = nil;
        end
    end
end

--- Clear all log entries.
function LogService:ClearLogs()
    local logs = self:GetLogs();
    for dayKey, _ in pairs(logs) do
        logs[dayKey] = nil;
    end
end

--- Get all log entries as a single string, newest day first.
-- @return string All log entries formatted for display.
function LogService:GetLogText()
    local logs = self:GetLogs();

    -- collect and sort day keys (newest first)
    local dayKeys = {};
    for dayKey, _ in pairs(logs) do
        table.insert(dayKeys, dayKey);
    end
    table.sort(dayKeys, function(a, b) return a > b; end);

    -- build text
    local lines = {};
    for _, dayKey in ipairs(dayKeys) do
        table.insert(lines, "--- " .. dayKey .. " ---");
        for _, entry in ipairs(logs[dayKey]) do
            table.insert(lines, entry);
        end
        table.insert(lines, "");
    end

    if (#lines == 0) then
        return "No log entries.";
    end

    return table.concat(lines, "\n");
end
end

