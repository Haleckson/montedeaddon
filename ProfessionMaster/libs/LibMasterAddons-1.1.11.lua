end

--- Forever style: move the header icon buttons of a window (settings, help,
--- ...) from the title bar to the bottom right corner under the content, the
--- first created one flush with the right window edge, the others to its
--- left. Called by the tab strip for tabbed windows; windows without tabs
--- call it after creating their buttons (they keep 30px of room at the
--- bottom). No-op in the flat style.
-- @param view View frame from CreateView.
-- @param offsetY Optional vertical shift of the button row in pixels.
function UiService:PlaceHeaderButtonsBottom(view, offsetY)
    local headerButtons = view.foreverHeaderButtons;
    if (not self:IsForever() or not headerButtons) then
        return;
    end
    local previous = nil;
    for _, button in ipairs(headerButtons) do
        button:ClearAllPoints();
        if (previous) then
            button:SetPoint("RIGHT", previous, "LEFT", -6, 0);
        else
            local sideInset = self:GetForeverInsets();
            button:SetPoint("BOTTOMRIGHT", view, "BOTTOMRIGHT", -sideInset, self:GetFrameMargin() * 3 - 2 + (offsetY or 0));
        end
        previous = button;
    end
    view.foreverHeaderButtons = nil;
end

-- create scroll frame
function UiService:CreateScrollFrame(container)
    -- create scroll frame and child
    local frameId = self.addon:GenerateString(10);
    local parentFrame = CreateFrame("Frame", self.addon.id .. "ScrollParent" .. frameId, container, BackdropTemplateMixin and "BackdropTemplate");
    local scrollFrame = CreateFrame("ScrollFrame", self.addon.id .. "Scroll" .. frameId, parentFrame, "UIPanelScrollFrameTemplate");
    local scrollChild = CreateFrame("Frame");
    parentFrame:SetBackdrop({
        bgFile = [[Interface\Buttons\WHITE8x8]]
    });
    parentFrame:SetBackdropColor(0, 0, 0, 0.5);

    -- get scroll object
    local scrollBarName = scrollFrame:GetName()
    local scrollBar = _G[scrollBarName .. "ScrollBar"];
    local scrollUpButton = _G[scrollBarName .. "ScrollBarScrollUpButton"];
    local scrollDownButton = _G[scrollBarName .. "ScrollBarScrollDownButton"];

    -- re-arrange scroll bar
    scrollUpButton:ClearAllPoints();
    scrollUpButton:SetPoint("TOPRIGHT", scrollFrame, "TOPRIGHT", -2, 0);
    scrollDownButton:ClearAllPoints();
    scrollDownButton:SetPoint("BOTTOMRIGHT", scrollFrame, "BOTTOMRIGHT", -2, 0);
    scrollBar:ClearAllPoints();
    scrollBar:SetPoint("TOP", scrollUpButton, "BOTTOM", -1, 0);
    scrollBar:SetPoint("BOTTOM", scrollDownButton, "TOP", -1, 0);

    -- add scroll child to scroll frame; the forever list keeps two more pixels
    -- of air to the controls above it (the list background moves along)
    local forever = self:IsForever();
    scrollFrame:SetScrollChild(scrollChild);
    scrollFrame:SetPoint("TOPLEFT", parentFrame, 5, forever and -7 or -5);
    scrollFrame:SetPoint("BOTTOMRIGHT", parentFrame, 0, 5);

    -- forever style: list background of the profession window, minimal scroll bar
    if (forever) then
        self:StyleForeverListBackground(parentFrame);
        self:StyleForeverScrollBar(scrollFrame);
    end
    return parentFrame, scrollChild, scrollFrame;
end

