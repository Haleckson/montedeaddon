clients apart (if GetSpellInfo then ... else C_Spell ...), so a global defined
here would change what every other addon does. A name the client offers
itself has no entry, compat.<name> reads the global then, at call time, so the
Classic clients call exactly what they called before, hooks included.

@author Kurki
@copyright ©2026 LibMasterAddons. All Rights Reserved.

