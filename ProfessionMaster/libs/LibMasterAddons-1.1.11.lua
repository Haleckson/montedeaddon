    backgroundBottomLeft:SetAtlas(FlatPanelAtlases.bottomLeft, true);
    backgroundBottomLeft:SetVertexColor(r, g, b, a);
    backgroundBottomLeft:SetPoint("BOTTOMLEFT", 2, 3);
    local backgroundBottomRight = view:CreateTexture(nil, "BACKGROUND", nil, -6);
    backgroundBottomRight:SetAtlas(FlatPanelAtlases.bottomRight, true);
    backgroundBottomRight:SetVertexColor(r, g, b, a);
    backgroundBottomRight:SetPoint("BOTTOMRIGHT", -2, 3);
    local backgroundBottom = view:CreateTexture(nil, "BACKGROUND", nil, -6);
    backgroundBottom:SetColorTexture(r, g, b, a);
    backgroundBottom:SetPoint("TOPLEFT", backgroundBottomLeft, "TOPRIGHT", 0, 0);
    backgroundBottom:SetPoint("BOTTOMRIGHT", backgroundBottomRight, "BOTTOMLEFT", 0, 0);
    local backgroundTop = view:CreateTexture(nil, "BACKGROUND", nil, -6);
    backgroundTop:SetColorTexture(r, g, b, a);
    backgroundTop:SetPoint("TOPLEFT", 2, -20);
    backgroundTop:SetPoint("BOTTOMRIGHT", backgroundBottomRight, "TOPRIGHT", 0, 0);
    local backgrounds = { backgroundBottomLeft, backgroundBottomRight, backgroundBottom, backgroundTop };
    view.foreverBackground = backgroundTop;

    -- portrait (normal windows only) on the window itself, so the ring of the
    -- frame above covers its edge: black disc behind the icon, the icon
    -- masked to a circle
    if (not isTool) then
        local ring = ModernPortraitRing;
        local portraitBackground = view:CreateTexture(nil, "ARTWORK", nil, 5);
        portraitBackground:SetTexture(PortraitMask);
        portraitBackground:SetVertexColor(0, 0, 0, 1);
        portraitBackground:SetSize(ring.diameter, ring.diameter);
        portraitBackground:SetPoint("CENTER", view, "TOPLEFT", ring.x, ring.y);
        view.portraitBackground = portraitBackground;

        local portrait = view:CreateTexture(nil, "ARTWORK", nil, 6);
        portrait:SetPoint("CENTER", view, "TOPLEFT", ring.x, ring.y);
        local mask = view:CreateMaskTexture();
        mask:SetTexture(PortraitMask, "CLAMPTOBLACKADDITIVE", "CLAMPTOBLACKADDITIVE");
        mask:SetAllPoints(portrait);
        portrait:AddMaskTexture(mask);
        view.portrait = portrait;
        view.portraitGeometry = ring;
        self:SetViewPortrait(view, nil);
    end

    -- frame of the client in an own frame above the window and its portrait
    local frameArt = CreateFrame("Frame", nil, view);
    frameArt:SetAllPoints(view);
    local layout = NineSliceUtil.GetLayout(isTool and ModernFrameLayouts.tool or ModernFrameLayouts.window);
    view.foreverFrame = self:ApplyModernFrameLayout(frameArt, layout);

    -- title above the frame: centered in the title bar next to the portrait
    -- like the game ui, in a tool window left in line with its content
    local titleHolder = CreateFrame("Frame", nil, view);
    titleHolder:SetAllPoints(view);
    titleHolder:SetFrameLevel(frameArt:GetFrameLevel() + 2);
    local titleLabel = view.titleLabel;
    titleLabel:SetParent(titleHolder);
    titleLabel:ClearAllPoints();
    if (isTool) then
        titleLabel:SetPoint("TOPLEFT", view, "TOPLEFT", 16, -5);
        titleLabel:SetPoint("RIGHT", view, "RIGHT", -42, 0);
        titleLabel:SetJustifyH("LEFT");
    else
        titleLabel:SetPoint("TOP", view, "TOP", 0, -5);
        titleLabel:SetPoint("LEFT", view, "LEFT", 60, 0);
        titleLabel:SetPoint("RIGHT", view, "RIGHT", -60, 0);
        titleLabel:SetJustifyH("CENTER");
    end
    titleLabel:SetWordWrap(false);

    -- close button of the game windows in the top right corner, above the
    -- frame; a view claims it through CreateFlatCloseButton
    local closeButton;
    if (C_Texture.GetAtlasInfo(ModernCloseButtonAtlases.normal)) then
        closeButton = CreateFrame("Button", nil, view);
        closeButton:SetSize(24, 24);
        closeButton:SetNormalAtlas(ModernCloseButtonAtlases.normal);
        closeButton:SetPushedAtlas(ModernCloseButtonAtlases.pushed);
        closeButton:SetDisabledAtlas(ModernCloseButtonAtlases.disabled);
        closeButton:SetHighlightAtlas(ModernCloseButtonAtlases.highlight, "ADD");
    else
        closeButton = self:CreateForeverCloseButton(view, nil, 22);
    end
    closeButton:SetPoint("TOPRIGHT", view, "TOPRIGHT", -2, 1);
    closeButton:SetFrameLevel(frameArt:GetFrameLevel() + 3);
    closeButton:Hide();
    view.foreverCloseButton = closeButton;

    -- tool windows: the backdrop alpha fades the background and the frame
    if (isTool) then
        self:AttachForeverToolFade(view, backgrounds);
    end
end

