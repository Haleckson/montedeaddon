--- Handle a game event.
-- @param name Event name.
-- @param callback Callback function, triggered with the event arguments.
function AddonContainer:HandleEvent(name, callback)
    -- register the event once, dispatch to all callbacks
    if (self.eventHandlers[name] == nil) then
        self.eventHandlers[name] = {};

        -- a client that does not know the event raises an error on register;
        -- the callback then simply never fires instead of breaking the caller
        if (not pcall(self.frame.RegisterEvent, self.frame, name)) then
            self:Log("Addon", "HandleEvent", "Event %s is unknown to this client", tostring(name));
        end
    end
    table.insert(self.eventHandlers[name], callback);
end

--- Register a callback for the own ADDON_LOADED (SavedVariables available).
--- Called immediately when the addon is already loaded.
-- @param callback Function(addon).
function AddonContainer:OnLoaded(callback)
    if (self.loaded) then
        callback(self);
        return;
    end
    table.insert(self.loadedHandlers, callback);
end

--- Register a callback fired when the player enters combat (after inCombat is set).
-- @param callback Function(addon).
function AddonContainer:OnCombatStart(callback)
    table.insert(self.combatStartHandlers, callback);
end

--- Register a callback fired when the player leaves combat.
-- @param callback Function(addon).
function AddonContainer:OnCombatEnd(callback)
    table.insert(self.combatEndHandlers, callback);
end

--- Register the container's own events: dispatcher, own ADDON_LOADED and
--- combat tracking (inCombat flag, used by views to stay hidden in combat).
function AddonContainer:RegisterEvents()
    local addon = self;

    -- dispatch to registered handlers
    self.frame:SetScript("OnEvent", function(_self, event, ...)
        local handlers = addon.eventHandlers[event];
        if (handlers) then
            for _, handler in ipairs(handlers) do
                handler(...);
            end
        end
    end);

    -- own addon loaded: SavedVariables are available from here on
    self:HandleEvent("ADDON_LOADED", function(loadedName)
        if (loadedName == addon.id and not addon.loaded) then
            addon.loaded = true;

            -- library hooks first (e.g. the ui style seed), then the addon handlers
            if (addon.lib.OnAddonLoaded) then
                addon.lib:OnAddonLoaded(addon);
            end
            for _, handler in ipairs(addon.loadedHandlers) do
                handler(addon);
            end
        end
    end);

    -- combat enter
    self:HandleEvent("PLAYER_REGEN_DISABLED", function()
        addon.inCombat = true;
        for _, handler in ipairs(addon.combatStartHandlers) do
            handler(addon);
        end
    end);

    -- combat leave
    self:HandleEvent("PLAYER_REGEN_ENABLED", function()
        addon.inCombat = nil;
        for _, handler in ipairs(addon.combatEndHandlers) do
            handler(addon);
        end
    end);
end
end

-- ==================== services/log-service.lua ====================
