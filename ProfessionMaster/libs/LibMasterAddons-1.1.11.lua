--- Dim the frame art along with a window: a view that darkens its window
--- with an overlay frame (black backdrop over the window rectangle) leaves
--- the frame pieces and the portrait ring outside that rectangle bright.
--- Black copies of the pieces in the overlay, anchored to the originals,
--- darken them by the same amount. No-op in the flat style.
-- @param view View frame from CreateView.
-- @param overlay Overlay frame of the view (child of the view).
function UiService:AttachDimArt(view, overlay)
    if (not view.foreverFrame or overlay.foreverDimArt) then
        return;
    end
    local copies = {};
    local function CreateCopy(original)
        local copy = overlay:CreateTexture(nil, "OVERLAY");
        local atlas = original.GetAtlas and original:GetAtlas();
        if (atlas) then
            copy:SetAtlas(atlas);
            copy:SetHorizTile(original:GetHorizTile());
            copy:SetVertTile(original:GetVertTile());
        else
            copy:SetTexture(original:GetTexture());
            copy:SetTexCoord(original:GetTexCoord());
        end
        copy:SetAllPoints(original);
        copy:SetVertexColor(0, 0, 0, 1);
        copy:SetAlpha(0.8);
        table.insert(copies, copy);
        return copy;
    end
    for _, piece in ipairs(view.foreverFrame) do
        CreateCopy(piece);
    end

    -- the portrait dims through a black disc over the whole inside of the
    -- ring, whatever icon shows there (tool windows have no ring)
    if (view.portraitBackground) then
        local portraitShade = overlay:CreateTexture(nil, "OVERLAY");
        portraitShade:SetTexture(PortraitMask);
        portraitShade:SetVertexColor(0, 0, 0, 1);
        portraitShade:SetAlpha(0.8);
        portraitShade:SetAllPoints(view.portraitBackground);
        table.insert(copies, portraitShade);
    end
    overlay.foreverDimArt = copies;
end

--- Set the portrait icon of a window (Forever style only, the flat style
--- has no portrait). Nil restores the addon icon of the toc.
-- @param view View frame from CreateView.
-- @param texture Texture path or file id.
function UiService:SetViewPortrait(view, texture)
    if (not view.portrait) then
        return;
    end
    -- without an explicit texture the addon logo shows (the portrait logo or
    -- the icon of the toc); explicit textures are game icons
    local icon = texture;
    local isLogo = false;
    if (not icon) then
        icon = self.addon.portraitIcon;
        if (not icon and C_AddOns and C_AddOns.GetAddOnMetadata) then
            icon = C_AddOns.GetAddOnMetadata(self.addon.id, "IconTexture");
        end
        isLogo = (icon ~= nil);
    end
    view.portrait:SetTexture(icon or [[Interface\Icons\INV_Misc_QuestionMark]]);

    -- logos are shown whole; game icons lose their baked button border and
    -- show a little larger, the black fill stays visible as a thin ring
    local ring = view.portraitGeometry or PortraitRing;
    if (isLogo) then
        view.portrait:SetSize(ring.logoSize, ring.logoSize);
        view.portrait:SetTexCoord(0, 1, 0, 1);
    else
        view.portrait:SetSize(ring.iconSize, ring.iconSize);
        view.portrait:SetTexCoord(ring.iconCrop, 1 - ring.iconCrop, ring.iconCrop, 1 - ring.iconCrop);
    end
end

--- Create the red panel button of the game ui with a caption.
-- @param container Parent frame.
-- @param text Caption.
-- @param onClick Click handler.
-- @return Button.
function UiService:CreateForeverButton(container, text, onClick)
    local button = CreateFrame("Button", nil, container, BackdropTemplateMixin and "BackdropTemplate");
    button:SetSize(80, 22);

    -- three slices of the button art
    local function CreateSlice(coords)
        local texture = button:CreateTexture(nil, "BACKGROUND");
        texture:SetTexture(PanelButtonTexture.up);
        texture:SetTexCoord(coords[1], coords[2], coords[3], coords[4]);
        return texture;
    end
    local left = CreateSlice(PanelButtonCoords.left);
    left:SetWidth(12);
    left:SetPoint("TOPLEFT", 0, 0);
    left:SetPoint("BOTTOMLEFT", 0, 0);
    local right = CreateSlice(PanelButtonCoords.right);
    right:SetWidth(12);
    right:SetPoint("TOPRIGHT", 0, 0);
    right:SetPoint("BOTTOMRIGHT", 0, 0);
    local middle = CreateSlice(PanelButtonCoords.middle);
    middle:SetPoint("TOPLEFT", left, "TOPRIGHT", 0, 0);
    middle:SetPoint("BOTTOMRIGHT", right, "BOTTOMLEFT", 0, 0);
    button.slices = { left, middle, right };

    -- swap the art with the button state
    local function SetArt(file)
        for _, slice in ipairs(button.slices) do
            slice:SetTexture(file);
        end
    end
    button:SetScript("OnMouseDown", function(self)
        if (self:IsEnabled()) then
            SetArt(PanelButtonTexture.down);
        end
    end);
    button:SetScript("OnMouseUp", function(self)
        if (self:IsEnabled()) then
            SetArt(PanelButtonTexture.up);
        end
    end);
    button:SetScript("OnDisable", function()
        SetArt(PanelButtonTexture.disabled);
    end);
    button:SetScript("OnEnable", function()
        SetArt(PanelButtonTexture.up);
    end);

    -- glow on hover
    local highlight = button:CreateTexture(nil, "HIGHLIGHT");
    highlight:SetTexture(PanelButtonTexture.highlight);
    highlight:SetTexCoord(PanelButtonCoords.full[1], PanelButtonCoords.full[2], PanelButtonCoords.full[3], PanelButtonCoords.full[4]);
    highlight:SetBlendMode("ADD");
    highlight:SetAllPoints();
    button:SetHighlightTexture(highlight);

    button:SetText(text);
    button:SetNormalFontObject("GameFontNormal");
    button:SetHighlightFontObject("GameFontHighlight");
    button:SetDisabledFontObject("GameFontDisable");
    button:SetScript("OnClick", onClick);
    return button;
end

--- Create a red icon button of the game ui (plus, minus, delete, arrows).
