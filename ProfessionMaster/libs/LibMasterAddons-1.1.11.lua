    local data = self:GetFrames()[frame.positionName];
    if (not data or not data.from) then
        frame:SetPoint("CENTER", 0, 0);
        return;
    end
    frame:SetPoint(data.from, nil, data.to, data.x, data.y);
end

-- store frame size
function UiService:StoreSize(frame)
    if (not self:GetFrames()[frame.positionName]) then
        self:GetFrames()[frame.positionName] = {};
    end
    self:GetFrames()[frame.positionName].width = frame:GetWidth();
    self:GetFrames()[frame.positionName].height = frame:GetHeight();
end

-- restore frame size
function UiService:RestoreSize(frame, defaultWidth, defaultHeight)
    local data = self:GetFrames()[frame.positionName];
    if (data and data.width and data.height) then
        -- enforce minimum size
        local minWidth = frame.minWidth or math.floor(defaultWidth * 0.67);
        local minHeight = frame.minHeight or math.floor(defaultHeight * 0.5);
        frame:SetWidth(math.max(data.width, minWidth));
        frame:SetHeight(math.max(data.height, minHeight));
    else
        frame:SetWidth(defaultWidth);
        frame:SetHeight(defaultHeight);
    end
end

-- validate that frame is visible on screen, reset to center if not
function UiService:ValidateOnScreen(frame)
    -- defer to next frame so layout is resolved
    C_Timer.After(0, function()
        local left = frame:GetLeft();
        local bottom = frame:GetBottom();
        local right = frame:GetRight();
        local top = frame:GetTop();
        if (not left or not bottom) then
            return;
        end

        local scale = frame:GetEffectiveScale();
        local screenWidth = GetScreenWidth();
        local screenHeight = GetScreenHeight();

        -- check if at least part of the frame is visible
        local visible = (right * scale > 0) and (left * scale < screenWidth) and (top * scale > 0) and (bottom * scale < screenHeight);
        if (not visible) then
            frame:ClearAllPoints();
            frame:SetPoint("CENTER", 0, 0);
        end
    end);
end

--- Create the minimap button (LibDBIcon launcher) of the addon. Ctrl+right-click
--- always hides the button (persisted in the settings table); everything else
--- is forwarded to config.onClick.
-- @param config Table:
--   icon        Texture path (default question mark icon).
--   label       Data broker label (default addon name).
--   settings    Table LibDBIcon stores its state in, needs .hide
--               (default <storagePrefix>_Settings.minimapButton).
--   overlayText Optional short text drawn over the icon (e.g. "TB").
--   onClick     Function(button) with "LeftButton"/"RightButton"; check
--               IsShiftKeyDown()/IsControlKeyDown() inside as needed.
--   onTooltip   Function(tooltip) filling the tooltip, or a list of lines
--               (the first line is the title).
--   onHidden    Function() called after ctrl+right-click hid the button
--               (e.g. to sync a settings checkbox).
-- @return The LibDBIcon minimap button.
function UiService:CreateMinimapIcon(config)
    config = config or {};
    local service = self;
    local addonId = self.addon.id;
    local libDbIcon = LibStub("LibDBIcon-1.0");
    local settings = config.settings or self:GetMinimapSettings();
    self.minimapSettings = settings;

    -- create / register data broker
    local dataObj = LibStub("LibDataBroker-1.1"):NewDataObject(addonId, {
        type = "launcher",
        label = config.label or self.addon.name,
        icon = config.icon or [[Interface\Icons\INV_Misc_QuestionMark]],
        OnClick = function(_, button)
            -- ctrl+right-click hides the button
            if (button == "RightButton" and IsControlKeyDown()) then
                service:SetMinimapIconShown(false);
                if (config.onHidden) then
                    config.onHidden();
                end
                return;
            end
            if (config.onClick) then
                config.onClick(button);
            end
        end,
        OnTooltipShow = function(tooltip)
            if (type(config.onTooltip) == "function") then
                config.onTooltip(tooltip);
            elseif (type(config.onTooltip) == "table") then
                for index, line in ipairs(config.onTooltip) do
                    if (index == 1) then
                        tooltip:SetText(line);
                    else
                        tooltip:AddLine(line);
                    end
                end
            else
                tooltip:SetText(config.label or service.addon.name);
            end
        end,
    });

    -- show minimap button
    libDbIcon:Register(addonId, dataObj, settings);
    local minimapButton = libDbIcon:GetMinimapButton(addonId);

    -- overlay a small label on the button so it is recognizable at a glance
    if (config.overlayText and minimapButton and not minimapButton.overlayLabel) then
        local overlayLabel = minimapButton:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall");
        overlayLabel:SetPoint("CENTER", 0, 0);
        overlayLabel:SetText("|cffffffff" .. config.overlayText .. "|r");
        minimapButton.overlayLabel = overlayLabel;
    end
    self.addon:Log("UiService", "CreateMinimapIcon", "minimap button registered (hidden: %s)", tostring(settings.hide));
    return minimapButton;
end

--- Get the minimap button settings table (<storagePrefix>_Settings.minimapButton,
--- created when missing so LibDBIcon can persist the position and hide state).
-- @return Settings table with .hide.
function UiService:GetMinimapSettings()
    if (self.minimapSettings) then
        return self.minimapSettings;
    end
    local settings = self.addon:GetSavedTable("Settings");
    if (not settings.minimapButton) then
        settings.minimapButton = { hide = false };
    end
    return settings.minimapButton;
end

--- Show or hide the minimap button and persist the state.
-- @param shown True to show, false to hide.
function UiService:SetMinimapIconShown(shown)
    local settings = self:GetMinimapSettings();
    settings.hide = not shown;
    local libDbIcon = LibStub("LibDBIcon-1.0");
    if (shown) then
        libDbIcon:Show(self.addon.id);
    else
        libDbIcon:Hide(self.addon.id);
    end
end

--- Check whether the minimap button is shown.
-- @return True when not hidden.
function UiService:IsMinimapIconShown()
    return not self:GetMinimapSettings().hide;
end
end

