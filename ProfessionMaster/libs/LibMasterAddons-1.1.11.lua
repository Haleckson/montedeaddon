--- Apply alternating row background color. Forever rows also get the yellow
--- hover; their shades are the pair the row backdrop draws as dark and light
--- stripe (see AttachForeverRowHover).
-- @param row Row frame with backdrop.
-- @param rowIndex 1-based row index for alternation.
function UiService:SetRowColor(row, rowIndex)
    if (self:IsForever()) then
        self:AttachForeverRowHover(row);
        local stripeShade = (rowIndex % 2 == 0) and 0.06 or 0.12;
        row.bgColor = stripeShade;
        row:SetBackdropColor(stripeShade, stripeShade, stripeShade, 0.5);
        return;
    end
    local backgroundColor = (rowIndex % 2 == 0) and 0.1 or 0.15;
    row.bgColor = backgroundColor;
    row:SetBackdropColor(backgroundColor, backgroundColor, backgroundColor, 0.5);
end

