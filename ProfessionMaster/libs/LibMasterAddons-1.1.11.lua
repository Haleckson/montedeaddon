--- Forever style: put one of the parchment backgrounds behind a list (the
--- files under textures\forever\backgrounds of the addon). The art covers the
--- list without distortion, the overhang is cut out of the texture, so its
--- burnt edge stays at the border of the list and never runs through the
--- middle of it.
-- @param scrollParent Parent frame of a scroll frame (from CreateScrollFrame).
-- @return Background object with SetArt(name), SetOpacity(alpha) and
--   Refresh(), or nil in the flat style.
function UiService:CreateForeverListBackground(scrollParent)
    if (not self:IsForever()) then
        return nil;
    end
    local service = self;
    local frame = CreateFrame("Frame", nil, scrollParent);
    frame:SetPoint("TOPLEFT", scrollParent, "TOPLEFT", 1, -1);
    frame:SetPoint("BOTTOMRIGHT", scrollParent, "BOTTOMRIGHT", -1, 1);

    -- stay below the scroll frame so the rows keep drawing on top
    frame:SetFrameLevel(scrollParent:GetFrameLevel());
    local texture = frame:CreateTexture(nil, "ARTWORK");
    texture:SetAllPoints(frame);
    texture:SetAlpha(0.9);

    local background = { frame = frame, texture = texture };

    --- Show one of the background files (name without path and extension).
    function background:SetArt(name)
        if (name == self.artName) then
            return;
        end
        self.artName = name;
        texture:SetTexture(service:GetForeverTexture("backgrounds\\" .. name));
        self:Refresh();
    end

    --- Set how strong the art shows through (default 0.9).
    function background:SetOpacity(alpha)
        texture:SetAlpha(alpha);
    end

    --- Fit the art to the current size of the list.
    function background:Refresh()
        local width = frame:GetWidth() or 0;
        local height = frame:GetHeight() or 0;
        if (not self.artName or width < 1 or height < 1) then
            texture:Hide();
            return;
        end

        -- scale by the larger factor, then show the part of the art that
        -- fits: the right end horizontally, the middle band vertically
        local scale = math.max(width / BackgroundContent.width, height / BackgroundContent.height);
        local visibleWidth = math.min(width / (BackgroundContent.width * scale), 1);
        local visibleHeight = math.min(height / (BackgroundContent.height * scale), 1);
        local contentBottom = BackgroundContent.height / BackgroundContent.sheet;
        texture:SetTexCoord(
            1 - visibleWidth, 1,
            contentBottom * (1 - visibleHeight) / 2, contentBottom * (1 + visibleHeight) / 2
        );
        texture:Show();
    end

    frame:SetScript("OnSizeChanged", function()
        background:Refresh();
    end);
    return background;
end

--- Attach the yellow row hover of the profession window to a row: the
--- brightest slice of the hover art stretched over the whole row (the
--- original fades out to both sides), drawn additively in gold. The gray
--- stripe shades the views set on the row backdrop are drawn as the stripes
--- of the dark list (see RowStripes), their gray hover is ignored; colored
--- backdrops (selections) keep working.
-- @param frame Row frame.
-- @param extraHoverRegions Optional child frames that keep the hover alive.
function UiService:AttachForeverRowHover(frame, extraHoverRegions)
    if (not frame.foreverHover) then
        local hover = frame:CreateTexture(nil, "BORDER", nil, -1);
        self:SetSheetPiece(hover, ProfessionsSheet, "rowHoverSolid");
        hover:SetAllPoints();
        hover:SetBlendMode("ADD");
        hover:SetVertexColor(1, 0.85, 0.45, 1);
        hover:Hide();
        frame.foreverHover = hover;
        frame.foreverHoverRegions = {};

        -- gray shades on the backdrop become the stripes, other colors pass
        if (frame.SetBackdropColor) then
            local setBackdropColor = frame.SetBackdropColor;
            frame.SetBackdropColor = function(self, r, g, b, a)
                if (r ~= g or g ~= b) then
                    setBackdropColor(self, r, g, b, a);
                    return;
                end

                -- the gray hover keeps what the row shows, the gold hover replaces it
                if (r >= RowStripes.hoverFrom) then
                    return;
                end

                -- transparent rows stay transparent
                if (a == 0) then
                    setBackdropColor(self, 0, 0, 0, 0);
                    return;
                end
                local stripe = (r >= RowStripes.lightFrom) and RowStripes.light or RowStripes.dark;
                setBackdropColor(self, stripe[1], stripe[2], stripe[3], stripe[4]);
            end;

            -- a stripe the view set before attaching is drawn again
            local r, g, b, a = frame:GetBackdropColor();
            local isGrayHover = r and r == g and g == b and r >= RowStripes.hoverFrom;
            if (r and not isGrayHover) then
                frame:SetBackdropColor(r, g, b, a);
            else
                frame:SetBackdropColor(0, 0, 0, 0);
            end
        end

        local function OnHoverEnter()
            if (frame.hoverGlowDisabled) then
                return;
            end
            hover:Show();
        end
        local function OnHoverLeave()
            if (frame:IsMouseOver()) then return; end
            hover:Hide();
        end
        frame.hoverGlowEnter = OnHoverEnter;
        frame.hoverGlowLeave = OnHoverLeave;
        frame.hoverGlowHide = function()
            hover:Hide();
        end;
        frame:HookScript("OnEnter", OnHoverEnter);
        frame:HookScript("OnLeave", OnHoverLeave);
        frame:HookScript("OnHide", function() hover:Hide(); end);
    end

    -- column regions of the row keep the hover alive
    if (extraHoverRegions) then
        for _, region in ipairs(extraHoverRegions) do
            if (not frame.foreverHoverRegions[region]) then
                frame.foreverHoverRegions[region] = true;
                region:HookScript("OnEnter", frame.hoverGlowEnter);
                region:HookScript("OnLeave", frame.hoverGlowLeave);
                region:HookScript("OnHide", frame.hoverGlowLeave);
            end
        end
    end
end

