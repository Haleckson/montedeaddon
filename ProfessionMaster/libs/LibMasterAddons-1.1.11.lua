--- Draw a single atlas as nine slice background of a frame (corners kept at
--- their size, edges and center stretched).
-- @param frame Frame to decorate.
-- @param atlasName Atlas name of the background art.
-- @param margins Slice margins in pixels of the art, one number for all
--        sides or { left, top, right, bottom }.
-- @param layer Draw layer (default "BACKGROUND").
-- @param outsetX Optional distance the art reaches out of the frame left and right.
-- @param outsetY Optional distance the art reaches out of the frame top and bottom.
function UiService:ApplyAtlasNineSlice(frame, atlasName, margins, layer, outsetX, outsetY)
    local info = C_Texture and C_Texture.GetAtlasInfo and C_Texture.GetAtlasInfo(atlasName);
    local file = info and (info.file or info.filename);
    if (not file) then
        return;
    end
    layer = layer or "BACKGROUND";

    -- slice margins: the rounded corners and the shadow of an art are often
    -- uneven, stretching them evenly smears the corners along the edges
    if (type(margins) ~= "table") then
        margins = { margins, margins, margins, margins };
    end
    local marginLeft, marginTop, marginRight, marginBottom = margins[1], margins[2], margins[3], margins[4];
    outsetX = outsetX or 0;
    outsetY = outsetY or 0;

    -- texture coordinates of the slice lines inside the atlas
    local left, right, top, bottom = info.leftTexCoord, info.rightTexCoord, info.topTexCoord, info.bottomTexCoord;
    local scaleX = (right - left) / info.width;
    local scaleY = (bottom - top) / info.height;
    local xs = { left, left + marginLeft * scaleX, right - marginRight * scaleX, right };
    local ys = { top, top + marginTop * scaleY, bottom - marginBottom * scaleY, bottom };

    -- nine pieces, columns and rows from top left to bottom right
    local pieces = {};
    for row = 1, 3 do
        for column = 1, 3 do
            local piece = frame:CreateTexture(nil, layer);
            piece:SetTexture(file);
            piece:SetTexCoord(xs[column], xs[column + 1], ys[row], ys[row + 1]);
            pieces[(row - 1) * 3 + column] = piece;
        end
    end

    -- corners at the size of their margins
    pieces[1]:SetPoint("TOPLEFT", -outsetX, outsetY);
    pieces[1]:SetSize(marginLeft, marginTop);
    pieces[3]:SetPoint("TOPRIGHT", outsetX, outsetY);
    pieces[3]:SetSize(marginRight, marginTop);
    pieces[7]:SetPoint("BOTTOMLEFT", -outsetX, -outsetY);
    pieces[7]:SetSize(marginLeft, marginBottom);
    pieces[9]:SetPoint("BOTTOMRIGHT", outsetX, -outsetY);
    pieces[9]:SetSize(marginRight, marginBottom);

    -- edges between the corners
    pieces[2]:SetPoint("TOPLEFT", pieces[1], "TOPRIGHT", 0, 0);
    pieces[2]:SetPoint("BOTTOMRIGHT", pieces[3], "BOTTOMLEFT", 0, 0);
    pieces[8]:SetPoint("TOPLEFT", pieces[7], "TOPRIGHT", 0, 0);
    pieces[8]:SetPoint("BOTTOMRIGHT", pieces[9], "BOTTOMLEFT", 0, 0);
    pieces[4]:SetPoint("TOPLEFT", pieces[1], "BOTTOMLEFT", 0, 0);
    pieces[4]:SetPoint("BOTTOMRIGHT", pieces[7], "TOPRIGHT", 0, 0);
    pieces[6]:SetPoint("TOPLEFT", pieces[3], "BOTTOMLEFT", 0, 0);
    pieces[6]:SetPoint("BOTTOMRIGHT", pieces[9], "TOPRIGHT", 0, 0);

    -- center
    pieces[5]:SetPoint("TOPLEFT", pieces[1], "BOTTOMRIGHT", 0, 0);
    pieces[5]:SetPoint("BOTTOMRIGHT", pieces[9], "TOPLEFT", 0, 0);
