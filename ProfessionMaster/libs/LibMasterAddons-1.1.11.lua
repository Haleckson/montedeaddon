--- Create header icon button with highlight.
-- @param container Parent frame.
-- @param icon Texture path for the icon.
-- @param tooltip Tooltip text.
-- @param onClick Callback function.
function UiService:CreateHeaderIconButton(container, icon, tooltip, onClick)
    -- create button frame
    local button = CreateFrame("Button", nil, container);
    button:SetSize(22, 22);

    -- add icon texture
    local iconTexture = button:CreateTexture(nil, "ARTWORK");
    iconTexture:SetAllPoints();
    iconTexture:SetTexture(icon);

    -- add highlight texture
    local highlight = button:CreateTexture(nil, "HIGHLIGHT");
    highlight:SetPoint("TOPLEFT", -1, 1);
