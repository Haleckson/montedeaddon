--[[

LibMasterAddons-1.0 — timer service

Named countdown timers (1-second ticker, no per-frame overhead), one-shot
waits and duration formatting.

@author Kurki
@copyright ©2026 LibMasterAddons. All Rights Reserved.

--]]

local Lib = LibStub:GetLibrary("LibMasterAddons-1.0", true);
if (not Lib or not Lib.isLoading) then
    return;
end

-- define built-in service
local TimerService = Lib:DefineService("timer");

--- Initialize service.
function TimerService:Initialize()
    self.timers = {};
end

--- Start a named countdown. A running timer with the same name is replaced.
-- @param name Timer name.
-- @param seconds Duration in seconds.
-- @param callback Function(secondsLeft), called immediately and every second.
function TimerService:Start(name, seconds, callback)
    -- stop existing timer with same name
    self:Stop(name);

    -- create timer state
    local timer = {
        seconds = seconds,
        callback = callback
    };
    self.timers[name] = timer;

    -- call with initial seconds
    callback(seconds);

    -- create a 1-second ticker (event-driven, no per-frame overhead)
    timer.ticker = C_Timer.NewTicker(1, function()
        timer.seconds = timer.seconds - 1;
        timer.callback(timer.seconds);

        -- check if 0 seconds reached
        if (timer.seconds <= 0) then
            self:Stop(name);
        end
    end, seconds);
end

--- Stop a named timer (no-op when not running).
-- @param name Timer name.
function TimerService:Stop(name)
    -- check timer
    if (self.timers[name] == nil) then
        return;
    end

    -- cancel ticker
    if (self.timers[name].ticker) then
        self.timers[name].ticker:Cancel();
    end
    self.timers[name] = nil;
end

--- Check whether a named timer is running.
-- @param name Timer name.
-- @return True while the timer runs.
function TimerService:IsRunning(name)
    return self.timers[name] ~= nil;
end

--- Run a callback once after the given seconds (named, replaceable).
-- @param name Timer name.
-- @param seconds Delay in seconds.
-- @param callback Function called when the delay elapsed.
function TimerService:Wait(name, seconds, callback)
    -- start timer
    self:Start(name, seconds, function(second)
        -- check if zero
        if (second == 0) then
            -- trigger callback
            callback();
        end
    end);
end

--- Format a duration in seconds into a human-readable time string.
-- @param seconds Number of seconds remaining.
-- @param omitZeroParts Leave out zero hour/minute parts above one hour (e.g. "2d 5m" instead of "2d 0h 5m").
-- @return Formatted time string (e.g. "5m 30s", "1d 2h 10m 5s", or colored "Ready").
function TimerService:FormatTime(seconds, omitZeroParts)
    -- ready state (locale key CooldownReady when the addon provides it)
    if (seconds <= 0) then
        local readyText = self:GetService("locale"):GetBare("CooldownReady") or "Ready";
        return "|cff00ff00" .. readyText .. "|r";
    end

    -- seconds only
    if (seconds < 60) then
        return string.format("%ds", seconds);
    end

    -- minutes only
    if (seconds < 3600) then
        local minutes = math.floor(seconds / 60);
        return string.format("%dm", minutes);
    end

    -- hours/days breakdown
    local days = math.floor(seconds / 86400);
    local hours = math.floor((seconds % 86400) / 3600);
    local minutes = math.floor((seconds % 3600) / 60);

    -- collect parts, optionally leaving out zero hours/minutes
    local parts = {};
    if (days > 0) then
        table.insert(parts, string.format("%dd", days));
    end
    if (hours > 0 or not omitZeroParts) then
        table.insert(parts, string.format("%dh", hours));
    end
    if (minutes > 0 or not omitZeroParts) then
        table.insert(parts, string.format("%dm", minutes));
    end
    return table.concat(parts, " ");
end
end

