--- Detect the running client. Returns the expansion flags shared by all
--- Master addons; also available on every addon container.
-- @return Table with isVanilla, isBcc, isWrath, isCata, isMop, isSod,
--         isForever, isRetail, is*AtLeast flags and the numeric expansionId
--         (1-5, SoD = 102). The classic flags describe the classic clients:
--         on WoW Forever and retail they are all false (expansionId 1).
function Lib:DetectClient()
    local wowBuild, _, _, interfaceNumber = GetBuildInfo();

    -- wow forever is a 1.60+ build on the modern engine without a project id
    -- of its own, only the interface number tells it apart (classic era is
    -- 115xx); it is not a vanilla client, so isVanilla stays false there
    local isForever = (interfaceNumber ~= nil) and (interfaceNumber >= 16000) and (interfaceNumber < 20000);

    -- retail (interface 100000 and up) builds 11.x and 12.x start with a "1"
    -- too, so isVanilla stays false there as well
    local isRetail = (interfaceNumber ~= nil) and (interfaceNumber >= 100000);
    local client = {
        isForever = isForever,
        isRetail = isRetail,
        isVanilla = (not isForever) and (not isRetail) and (string.find(wowBuild, "1.") == 1),
        isBcc = string.find(wowBuild, "2.") == 1,
        isWrath = string.find(wowBuild, "3.") == 1,
        isCata = string.find(wowBuild, "4.") == 1,
        isMop = string.find(wowBuild, "5.") == 1,
    };

    -- season of discovery runs on the vanilla client
    client.isSod = client.isVanilla and C_Seasons and C_Seasons.HasActiveSeason and C_Seasons.HasActiveSeason() and (C_Seasons.GetActiveSeason() == 2) or false;

    -- "at least" indicators
    client.isMopAtLeast = client.isMop;
    client.isCataAtLeast = client.isCata or client.isMopAtLeast;
    client.isWrathAtLeast = client.isWrath or client.isCataAtLeast;
    client.isBccAtLeast = client.isBcc or client.isWrathAtLeast;

    -- numeric expansion identifier (used in exports and sync payloads)
    client.expansionId = client.isSod and 102 or client.isMop and 5 or client.isCata and 4 or client.isWrath and 3 or client.isBcc and 2 or 1;
    return client;
end

--- Create a new addon container.
-- @param config Table: id (required), name, shortcut, storagePrefix, version.
-- @return Addon container.
function Lib:CreateAddon(config)
    assert(type(config) == "table" and type(config.id) == "string", "LibMasterAddons: CreateAddon needs a config table with an id");

    -- resolve version from the toc; the dev workspace ships the unstamped
    -- placeholder 0.0.1, which identifies a dev client
    local version = config.version or (C_AddOns and C_AddOns.GetAddOnMetadata(config.id, "Version")) or "0.0.1";

    -- create addon with identity, client flags and empty registries
    local addon = self:DetectClient();
    addon.lib = self;
    addon.compat = self.compat;
    addon.id = config.id;
    addon.name = config.name or config.id;
    addon.version = version;
    addon.shortcut = config.shortcut or ("[" .. addon.name .. "] ");
    addon.storagePrefix = config.storagePrefix or config.id;
    addon.frame = CreateFrame("Frame");
    addon.loaded = false;
    addon.devMode = (version == "0.0.1");
    addon.isDebug = addon.devMode;
    addon.serviceTypes = {};
    addon.services = {};
    addon.viewTypes = {};
    addon.modelTypes = {};
    addon.eventHandlers = {};
    addon.loadedHandlers = {};
    addon.combatStartHandlers = {};
    addon.combatEndHandlers = {};
    setmetatable(addon, AddonContainer);

    -- wire lifecycle events and remember the addon
    addon:RegisterEvents();
    self.addons[addon.id] = addon;
    return addon;
end

