--- Draw the Forever window art on a view like the PortraitFrameTemplate of
--- the game ui: rock background, title bar with the title, portrait ring,
--- thin metal borders and the red close button in the top right corner. The
--- portrait shows the addon icon of the toc until a view sets its own (see
--- SetViewPortrait).
-- @param view View frame from CreateView.
-- @param isTool True for a tool window (corner without portrait).
-- @param isOverlay True for an overlay mini window (thin dialog frame).
function UiService:CreateForeverWindowArt(view, isTool, isOverlay)
    if (isOverlay) then
        self:CreateForeverOverlayArt(view);
        return;
    end

    -- modern clients draw their windows with the NineSlice frame of their own art
    if (self:HasModernFrame()) then
        self:CreateModernWindowArt(view, isTool);
        return;
    end

    -- a piece of the frame kit at the size of its art; tiling pieces repeat
    -- their pattern along the window instead of stretching it
    local function CreatePiece(atlasName, layer, subLevel)
        local texture = view:CreateTexture(nil, layer or "BORDER", nil, subLevel or 0);
        texture:SetAtlas(atlasName, true);
        if (string.sub(atlasName, 1, 1) == "_") then
            texture:SetHorizTile(true);
        elseif (string.sub(atlasName, 1, 1) == "!") then
            texture:SetVertTile(true);
        end
        return texture;
    end

    -- opaque rock background below the title bar
    local background = view:CreateTexture(nil, "BACKGROUND", nil, -6);
    background:SetTexture(RockBackground, "REPEAT", "REPEAT");
    background:SetHorizTile(true);
    background:SetVertTile(true);
    background:SetPoint("TOPLEFT", 2, -21);
    background:SetPoint("BOTTOMRIGHT", -2, 2);
    background:SetVertexColor(0.85, 0.85, 0.85, 1);
    view.foreverBackground = background;

    -- title bar: its dark background, the streaks below it
    local titleBackground = CreatePiece(FrameAtlases.titleBackground, "BACKGROUND", -5);
    titleBackground:SetPoint("TOPLEFT", 2, -3);
    titleBackground:SetPoint("TOPRIGHT", -25, -3);
    local titleStreaks = CreatePiece(FrameAtlases.titleStreaks, "BORDER", -1);
    titleStreaks:SetPoint("TOPLEFT", 0, -21);
    titleStreaks:SetPoint("TOPRIGHT", -2, -21);

    -- top corners: the portrait ring (its art starts the title bar) or the
    -- plain corner of a tool window, the title bar border runs between them
    local topRight = CreatePiece(FrameAtlases.cornerTopRight);
    topRight:SetPoint("TOPRIGHT", 0, 1);
    local topLeft;
    local titleTile = CreatePiece(FrameAtlases.titleTile);
    if (isTool) then
        topLeft = CreatePiece(FrameAtlases.cornerTopLeft);
        topLeft:SetPoint("TOPLEFT", -6, 1);
        titleTile:SetPoint("TOPLEFT", topLeft, "TOPRIGHT", 0, 0);
    else
        topLeft = view:CreateTexture(nil, "ARTWORK", nil, 6);
        topLeft:SetAtlas(FrameAtlases.portrait, true);
        topLeft:SetPoint("TOPLEFT", view, "TOPLEFT", PortraitRing.x - 36.5, PortraitRing.y + 34);
        titleTile:SetPoint("TOPLEFT", topLeft, "TOPRIGHT", 0, -10);
        view.portraitRing = topLeft;
    end
    titleTile:SetPoint("TOPRIGHT", topRight, "TOPLEFT", 0, 0);

    -- bottom corners and the borders between all corners
    local bottomLeft = CreatePiece(FrameAtlases.cornerBottomLeft);
    bottomLeft:SetPoint("BOTTOMLEFT", -6, -5);
    local bottomRight = CreatePiece(FrameAtlases.cornerBottomRight);
    bottomRight:SetPoint("BOTTOMRIGHT", 0, -5);
    local edgeBottom = CreatePiece(FrameAtlases.edgeBottom);
    edgeBottom:SetPoint("BOTTOMLEFT", bottomLeft, "BOTTOMRIGHT", 0, 0);
    edgeBottom:SetPoint("BOTTOMRIGHT", bottomRight, "BOTTOMLEFT", 0, 0);
    local edgeLeft = CreatePiece(FrameAtlases.edgeLeft);
    if (isTool) then
        edgeLeft:SetPoint("TOPLEFT", topLeft, "BOTTOMLEFT", 0, 0);
    else
        edgeLeft:SetPoint("TOPLEFT", topLeft, "BOTTOMLEFT", 8, 0);
    end
    edgeLeft:SetPoint("BOTTOMLEFT", bottomLeft, "TOPLEFT", 0, 0);
    local edgeRight = CreatePiece(FrameAtlases.edgeRight);
    edgeRight:SetPoint("TOPRIGHT", topRight, "BOTTOMRIGHT", 1, 0);
    edgeRight:SetPoint("BOTTOMRIGHT", bottomRight, "TOPRIGHT", 0, 0);
    view.foreverFrame = { titleBackground, titleStreaks, topLeft, topRight, titleTile, bottomLeft, bottomRight, edgeBottom, edgeLeft, edgeRight };

    -- portrait (normal windows only): the frame lies lowest, the black disc
    -- covers it inside the ring, the ring sits on the disc, the icon on top
    if (not isTool) then
        -- black disc filling the ring so neither the window background nor the
        -- rim of an icon shows through. The mask art fades out towards its
        -- edge, so the disc is drawn well past the opening and ends under the
        -- ring
        local portraitBackground = view:CreateTexture(nil, "ARTWORK", nil, 5);
        portraitBackground:SetTexture(PortraitMask);
        portraitBackground:SetVertexColor(0, 0, 0, 1);
        portraitBackground:SetSize(PortraitRing.diameter + 12, PortraitRing.diameter + 12);
        portraitBackground:SetPoint("CENTER", view, "TOPLEFT", PortraitRing.x, PortraitRing.y);
        view.portraitBackground = portraitBackground;

        -- round portrait centered in the ring, masked to a circle so no edge shows
        local portrait = view:CreateTexture(nil, "ARTWORK", nil, 7);
        portrait:SetPoint("CENTER", view, "TOPLEFT", PortraitRing.x, PortraitRing.y);
        local mask = view:CreateMaskTexture();
        mask:SetTexture(PortraitMask, "CLAMPTOBLACKADDITIVE", "CLAMPTOBLACKADDITIVE");
        mask:SetAllPoints(portrait);
        portrait:AddMaskTexture(mask);
        view.portrait = portrait;
        self:SetViewPortrait(view, nil);
    end

    -- title in the title bar, never wrapped: centered next to the portrait
    -- like the game ui, in a tool window left in line with its content (item
    -- names of the mini views, logo of the help windows)
    local titleLabel = view.titleLabel;
    titleLabel:ClearAllPoints();
    if (isTool) then
        titleLabel:SetPoint("TOPLEFT", view, "TOPLEFT", 16, -5);
        titleLabel:SetPoint("RIGHT", view, "RIGHT", -42, 0);
        titleLabel:SetJustifyH("LEFT");
    else
        titleLabel:SetPoint("TOP", view, "TOP", 0, -5);
        titleLabel:SetPoint("LEFT", view, "LEFT", 60, 0);
        titleLabel:SetPoint("RIGHT", view, "RIGHT", -60, 0);
        titleLabel:SetJustifyH("CENTER");
    end
    titleLabel:SetWordWrap(false);

    -- red close button in the top right corner of the title bar, where the
    -- game ui puts its close button; a view claims it through
    -- CreateFlatCloseButton and binds its click there
    local closeButton = self:CreateForeverCloseButton(view, nil, 22);
    closeButton:SetPoint("TOPRIGHT", view, "TOPRIGHT", -1, 0);
    closeButton:Hide();
    view.foreverCloseButton = closeButton;

    -- tool windows: the backdrop alpha fades the rock background and the frame
    if (isTool) then
        self:AttachForeverToolFade(view, { background });
    end
end

--- Fade the art of a tool window with the backdrop calls of its view: the
--- background alpha a view sets through SetBackdropColor (the transparency
--- settings of the overlays) fades the background, the border alpha of
--- SetBackdropBorderColor fades the frame with its title bar, so a mini
--- window that hides its border while it is not hovered hides the frame as
--- well; windows that never set a border keep the frame solid.
-- @param view View frame with foreverFrame.
-- @param backgrounds Background regions of the window.
function UiService:AttachForeverToolFade(view, backgrounds)
    local setBackdropColor = view.SetBackdropColor;
    view.SetBackdropColor = function(frame, r, g, b, a)
        setBackdropColor(frame, 0, 0, 0, 0);
        for _, background in ipairs(backgrounds) do
            background:SetAlpha(a or 1);
        end
    end;
    local setBackdropBorderColor = view.SetBackdropBorderColor;
    view.SetBackdropBorderColor = function(frame, r, g, b, a)
        setBackdropBorderColor(frame, 0, 0, 0, 0);
        for _, piece in ipairs(view.foreverFrame) do
            piece:SetAlpha(a or 1);
        end
    end;
end

--- Check whether the client draws its windows with the modern NineSlice
--- frame (WoW Forever): both layouts the windows need exist.
-- @return True for the modern frame.
function UiService:HasModernFrame()
    if (not NineSliceUtil or not NineSliceUtil.GetLayout or not C_Texture or not C_Texture.GetAtlasInfo) then
        return false;
    end
    return NineSliceUtil.GetLayout(ModernFrameLayouts.window) ~= nil and NineSliceUtil.GetLayout(ModernFrameLayouts.tool) ~= nil;
end

--- Draw the pieces of a NineSlice layout of the game on a frame, the way the
--- game sets them up (corners at the size of their art, edges between the
--- corners, tiling edges repeat).
-- @param container Frame the pieces are drawn on.
-- @param layout NineSlice layout table of the game.
-- @return List of the piece textures.
function UiService:ApplyModernFrameLayout(container, layout)
    local pieces = {};
    local piecesByName = {};
    for _, setup in ipairs(ModernFramePieces) do
        local pieceLayout = layout[setup.name];
        local atlasInfo = pieceLayout and C_Texture.GetAtlasInfo(pieceLayout.atlas);
        local from = setup.from and piecesByName[setup.from];
        local to = setup.to and piecesByName[setup.to];
        if (atlasInfo and (not setup.from or (from and to))) then
            local piece = container:CreateTexture(nil, pieceLayout.layer or "BORDER", nil, pieceLayout.subLevel);
            if (setup.from) then
                piece:SetPoint(setup.point, from, setup.relativePoint, pieceLayout.x or 0, pieceLayout.y or 0);
                piece:SetPoint(setup.relativePoint, to, setup.point, pieceLayout.x1 or 0, pieceLayout.y1 or 0);
            else
                piece:SetPoint(pieceLayout.point or setup.point, container, pieceLayout.relativePoint or setup.point, pieceLayout.x or 0, pieceLayout.y or 0);
            end
            piece:SetAtlas(pieceLayout.atlas, true);
            piece:SetHorizTile(atlasInfo.tilesHorizontally or false);
            piece:SetVertTile(atlasInfo.tilesVertically or false);

            -- the game turns off pixel snapping for these frames
            if (layout.disableSharpening and piece.SetTexelSnappingBias) then
                piece:SetTexelSnappingBias(0);
                piece:SetSnapToPixelGrid(false);
            end
            piecesByName[setup.name] = piece;
            table.insert(pieces, piece);
        end
    end
    return pieces;
end

--- Draw the window art of the modern clients (WoW Forever) like the game
--- draws its own windows (PortraitFrameFlatTemplate, the bags): dark panel
--- background, the NineSlice frame of the client with the portrait ring in
--- its top left corner (tool windows: plain corner), the title in the title
--- bar and the red close button. The frame lies above the portrait and
--- below the title, like in the game templates.
