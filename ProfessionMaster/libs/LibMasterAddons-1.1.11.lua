LibMasterAddons-1.0 — client compatibility

The WoW Forever client (1.60.x) and retail run on the modern engine: the
global api functions the Classic clients still offer were moved into C_
namespaces and ChatFrameUtil there, without the deprecation fallbacks. The
Master addons are written against the Classic api, so every Classic function
that is missing on the running client is offered in Lib.compat on top of its
replacement. Every addon container carries the table as addon.compat, and the
addons call these functions through it (self.addon.compat.GetItemInfo(...)),
