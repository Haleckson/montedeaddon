-- define built-in service
local LocaleService = Lib:DefineService("locale");

--- Initialize service.
function LocaleService:Initialize()
    -- get current locale name and all locales of the addon
    local fullLocaleName = GetLocale();
    local shortLocaleName = string.sub(fullLocaleName, 1, 2);
    local localesModel = self:GetModel("locales");
    local locales = localesModel and localesModel:Create() or {};
    self.localeName = fullLocaleName;

    -- try full locale first (e.g. zhCN, zhTW), then short (e.g. en, de)
    if (locales[fullLocaleName]) then
        self.current = locales[fullLocaleName];
        return;
    end

    if (locales[shortLocaleName]) then
        self.current = locales[shortLocaleName];
        return;
    end

    -- use english locale; an addon without locales model gets the keys back
    self.current = locales["en"] or {};
end

--- Get a formatted text. Without format arguments the text is returned as-is:
--- percent signs belonging to the text itself (e.g. a %player% placeholder)
--- are no format options and would raise "invalid option in format".
-- @param name Locale key.
-- @param ... Optional string.format arguments.
-- @return Localized text (the key when missing).
function LocaleService:Get(name, ...)
    local text = self.current[name];
    if (text == nil) then
        return name;
    end
    if (select("#", ...) == 0) then
        return text;
    end
    return string.format(text, ...);
end

--- Get the bare locale value (nil when missing).
-- @param name Locale key.
-- @return Raw value or nil.
function LocaleService:GetBare(name)
    return self.current[name];
end

--- Check whether a locale key exists.
-- @param name Locale key.
-- @return True when the key has a text.
function LocaleService:Has(name)
    return self.current[name] ~= nil;
end
