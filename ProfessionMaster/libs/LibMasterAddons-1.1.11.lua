--- Get a SavedVariables table of this addon by suffix, e.g. "Logs" resolves
--- to the global <storagePrefix>_Logs. The table is created when missing and
--- always read from the global, so the stored table replaces it on load.
-- @param suffix Storage suffix.
-- @return Global storage table.
function AddonContainer:GetSavedTable(suffix)
    local globalName = self.storagePrefix .. "_" .. suffix;
    if (_G[globalName] == nil) then
        _G[globalName] = {};
