--- Get (and lazily create) a service instance. Addon-specific types win over
--- the built-in library services.
-- @param name Name of service.
-- @return Service instance.
function AddonContainer:GetService(name)
    if (self.services[name] == nil) then
        local serviceType = self.serviceTypes[name] or self.lib.serviceTypes[name];
        assert(serviceType, "LibMasterAddons: unknown service '" .. tostring(name) .. "' in addon " .. self.id);

        -- create service with injected helpers
        local addon = self;
        local service = {
            addon = addon,
            GetService = function(_self, serviceName)
                return addon:GetService(serviceName);
            end,
            GetModel = function(_self, modelName)
                return addon:GetModel(modelName);
            end,
            HandleEvent = function(_self, eventName, callback)
                return addon:HandleEvent(eventName, callback);
            end
        };
        setmetatable(service, serviceType);
        self.services[name] = service;

        -- initialize service
        if (service.Initialize) then
            service:Initialize();
        end
    end
    return self.services[name];
end

