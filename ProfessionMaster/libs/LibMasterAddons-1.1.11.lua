    holder:SetPoint("TOPLEFT", CardPadding, -CardPadding);
    holder:SetPoint("TOPRIGHT", -CardPadding, -CardPadding);
    holder:SetHeight(PreviewHolderHeight);
    holder:SetBackdrop({
        bgFile = [[Interface\Buttons\WHITE8x8]],
    });
    holder:SetBackdropColor(0, 0, 0, 0.45);
    holder:SetClipsChildren(true);
    card.preview = self:CreateStylePreview(holder, style);

    -- name with a check mark while selected
    local nameLabel = card:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge");
    nameLabel:SetPoint("TOPLEFT", holder, "BOTTOMLEFT", 2, -8);
    nameLabel:SetText(name);
    local check = card:CreateTexture(nil, "OVERLAY");
    check:SetTexture([[Interface\Buttons\UI-CheckBox-Check]]);
    check:SetSize(22, 22);
    check:SetPoint("LEFT", nameLabel, "RIGHT", 2, 1);

    local descriptionLabel = card:CreateFontString(nil, "OVERLAY", "GameFontHighlightSmall");
    descriptionLabel:SetPoint("TOPLEFT", nameLabel, "BOTTOMLEFT", 0, -4);
    descriptionLabel:SetPoint("RIGHT", card, "RIGHT", -CardPadding, 0);
    descriptionLabel:SetJustifyH("LEFT");
    descriptionLabel:SetTextColor(0.8, 0.8, 0.8);
    descriptionLabel:SetText(description);

    -- click catcher above the preview: the small window only shows, the whole
    -- card selects
    local catcher = CreateFrame("Button", nil, card);
    catcher:SetAllPoints(card);
    catcher:SetFrameLevel(card:GetFrameLevel() + 60);
    local selected = false;
    local hovered = false;
    local function Paint()
        local colors = selected and CardColors.selected or (hovered and CardColors.hover or CardColors.normal);
        card:SetBackdropColor(unpack(colors.background));
        card:SetBackdropBorderColor(unpack(colors.border));
        check:SetShown(selected);
    end
    catcher:SetScript("OnEnter", function()
        hovered = true;
        Paint();
    end);
    catcher:SetScript("OnLeave", function()
        hovered = false;
        Paint();
    end);
    catcher:SetScript("OnClick", function()
        PlaySound(SOUNDKIT and SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_ON or 856);
        onSelect(style);
    end);

    function card:SetSelected(isSelected)
        selected = isSelected;
        Paint();
    end
    Paint();
    return card;
end

--- Build the preview of a style: the factories draw in the style of the
--- session, so the style is switched for the time the preview is built and
--- restored afterwards, even when building fails.
-- @param holder Frame the preview is centered in.
-- @param style "forever" or "flat".
-- @return Preview object with ShowHighlight(), or nil.
function UiService:CreateStylePreview(holder, style)
    local sessionStyle = self:GetStyle();
    Lib.uiStyle = style;
    local ok, result = pcall(self.BuildStylePreview, self, holder, style);
    Lib.uiStyle = sessionStyle;
    if (not ok) then
        self.addon:Log("UiService", "CreateStylePreview", "preview of %s failed: %s", style, tostring(result));
        return nil;
    end
    return result;
end

--- Draw the purple to gold border of a flat window (visible, the real
--- windows show it while they are moved).
-- @param window Window frame.
local function CreateFlatBorder(window)
    local purple = { 0.6, 0.3, 0.9 };
    local gold = { 0.95, 0.65, 0.15 };
    local function Mix(t)
        return { purple[1] + (gold[1] - purple[1]) * t, purple[2] + (gold[2] - purple[2]) * t, purple[3] + (gold[3] - purple[3]) * t };
    end
    local function Border(point1, point2, orientation, from, to, isHorizontal)
        local texture = window:CreateTexture(nil, "BORDER");
        texture:SetTexture([[Interface\Buttons\WHITE8x8]]);
        texture:SetPoint(point1, window, point1, 0, 0);
        texture:SetPoint(point2, window, point2, 0, 0);
        if (isHorizontal) then
            texture:SetHeight(1);
        else
            texture:SetWidth(1);
        end
        if (texture.SetGradientAlpha) then
            texture:SetGradientAlpha(orientation, from[1], from[2], from[3], 1, to[1], to[2], to[3], 1);
        else
            texture:SetGradient(orientation, CreateColor(from[1], from[2], from[3], 1), CreateColor(to[1], to[2], to[3], 1));
        end
        texture:SetAlpha(0.8);
    end
    Border("TOPLEFT", "TOPRIGHT", "HORIZONTAL", purple, Mix(0.8), true);
    Border("BOTTOMLEFT", "BOTTOMRIGHT", "HORIZONTAL", Mix(0.2), gold, true);
    Border("TOPLEFT", "BOTTOMLEFT", "VERTICAL", Mix(0.2), purple, false);
    Border("TOPRIGHT", "BOTTOMRIGHT", "VERTICAL", gold, Mix(0.8), false);
end

--- Build the small window of a preview with the factories of the active
--- style (see CreateStylePreview): frame, title, close button, two tabs, a
--- search field, a list with one highlighted row and a button.
-- @param holder Frame the preview is centered in.
-- @param style "forever" or "flat".
-- @return Preview object with ShowHighlight().
function UiService:BuildStylePreview(holder, style)
    local forever = (style == Lib.UiStyles.Forever);
    local service = self;
    local preview = {};

    -- window
    local window = CreateFrame("Frame", nil, holder, BackdropTemplateMixin and "BackdropTemplate");
    window:SetSize(PreviewWidth, PreviewHeight);
    window:SetScale(PreviewScale);
    window:SetPoint("CENTER", holder, "CENTER", 0, 0);
    window:SetBackdrop({
        bgFile = [[Interface\Buttons\WHITE8x8]],
    });
    local titleLabel = window:CreateFontString(nil, "OVERLAY", "GameFontNormalLeft");
    titleLabel:SetPoint("TOPLEFT", 16, -14);
    titleLabel:SetText(self.addon.name);
    window.titleLabel = titleLabel;
    if (forever) then
        window:SetBackdropColor(0, 0, 0, 0);
        self:CreateForeverWindowArt(window, false);
        window.foreverCloseButton:Show();
    else
        window:SetBackdropColor(0, 0, 0, 0.8);
        CreateFlatBorder(window);
        local closeButton = self:CreateFlatCloseButton(window, nil);
        closeButton:SetSize(22, 22);
        closeButton:SetPoint("TOPRIGHT", -12, -8);
    end

    -- content frame with the insets of the main windows
    local sideInset, headerHeight, footerHeight = 12, 60, 30;
    if (forever) then
        sideInset, headerHeight, footerHeight = self:GetForeverInsets();
    end
    local content = CreateFrame("Frame", nil, window, BackdropTemplateMixin and "BackdropTemplate");
    content:SetBackdrop({
        bgFile = [[Interface\Buttons\WHITE8x8]],
    });
    content:SetBackdropColor(0, 0, 0, 0.5);
    content:SetPoint("TOPLEFT", sideInset, -headerHeight);
    content:SetPoint("BOTTOMRIGHT", -sideInset, footerHeight);
    for _, side in ipairs({ "BOTTOM", "LEFT", "RIGHT" }) do
        local border = content:CreateTexture(nil, "BORDER");
        border:SetColorTexture(0.5, 0.5, 0.5, 0.5);
        if (side == "BOTTOM") then
            border:SetHeight(1);
            border:SetPoint("BOTTOMLEFT", 0, 0);
            border:SetPoint("BOTTOMRIGHT", 0, 0);
        else
            border:SetWidth(1);
            border:SetPoint("TOP" .. side, 0, 0);
            border:SetPoint("BOTTOM" .. side, 0, 0);
        end
    end

    -- two tabs
    local strip = self:CreateTabStrip(window, content, { tabWidth = 120 });
    local firstTab = strip:AddTab(TRADE_SKILLS or "Professions", nil);
    strip:AddTab(GUILD or "Guild", nil);
    strip:SetActive(firstTab);

    -- search field
    local search = self:CreateEditBox(content, 170);
    search:SetPoint("TOPLEFT", 8, -8);
    search:SetPlaceholder(SEARCH or "Search");

    -- list rows
    local highlightRow;
    for index, entry in ipairs(PreviewRows) do
        local row = CreateFrame("Button", nil, content, BackdropTemplateMixin and "BackdropTemplate");
        row:SetBackdrop({
            bgFile = [[Interface\Buttons\WHITE8x8]],
            edgeFile = [[Interface\Buttons\WHITE8x8]],
            edgeSize = 1,
        });
        row:SetBackdropBorderColor(0, 0, 0, 0);
        row:SetHeight(20);
        row:SetPoint("TOPLEFT", 8, -(38 + (index - 1) * 21));
        row:SetPoint("RIGHT", content, "RIGHT", -8, 0);
        self:SetRowColor(row, index);
        local nameText = row:CreateFontString(nil, "OVERLAY", "GameFontHighlight");
        nameText:SetPoint("LEFT", 6, 0);
        nameText:SetText("|T" .. entry.icon .. ":14:14|t  " .. GetSpellName(entry.spellId));
        local skillText = row:CreateFontString(nil, "OVERLAY", "GameFontNormal");
        skillText:SetPoint("RIGHT", -8, 0);
        skillText:SetText(entry.skill);
        if (index == 2) then
            highlightRow = row;
        end
    end

    -- button in the footer
    local button = self:CreateFlatButton(window, OKAY or "OK", nil);
    button:SetSize(90, 22);
    button:SetPoint("BOTTOMRIGHT", -sideInset, forever and (self:GetFrameMargin() * 3 - 2) or 4);

    --- Show the hover look of the highlighted row (the classic hover hides with
    --- its row, so it is shown again whenever the dialog shows).
    function preview:ShowHighlight()
        if (forever) then
            if (highlightRow.foreverHover) then
                highlightRow.foreverHover:Show();
            end
            return;
        end
        highlightRow:SetBackdropColor(unpack(service.HoverBackdropColor));
        highlightRow:SetBackdropBorderColor(unpack(service.HoverBorderColor));
    end

    preview.window = window;
    return preview;
end
