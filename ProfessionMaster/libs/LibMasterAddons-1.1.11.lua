--- Create a tab strip above a content frame: flat tab buttons (borders on
--- left, right and top, the active one taller with a glow) that sit on the top
--- border of the content frame, which gets a gap under the active tab. The
--- tabs are clipped to the width of the content frame; when they do not fit,
--- two arrow buttons appear at the right end to scroll them tab by tab (the
--- mouse wheel over the tabs scrolls as well), like a classic tab control.
-- @param view Frame the strip and the arrows are created in.
-- @param contentFrame Frame the tabs sit on (its top border must be left to
--   the strip: it draws the top border segments itself).
-- @param config Optional table: glowTexture (texture of the active tab glow),
--   tabWidth (125), tabGap (4), activeHeight (26), inactiveHeight (24),
--   sideInset (6, distance of the first tab and the arrows to the edges),
--   leftInset (distance of the first tab to the left edge, 48 in the forever
--   style to clear the portrait ring).
-- @return Strip object with AddTab(caption, onClick) → button,
--   SetActive(button), SetBadge(button, count), Layout(), ScrollToTab(button);
--   the buttons expose GetFontString, SetHeight etc. as normal buttons.
function UiService:CreateTabStrip(view, contentFrame, config)
    config = config or {};
    local forever = self:IsForever();
    local tabWidth = config.tabWidth or 125;
    local tabGap = config.tabGap or (forever and 2 or 4);
    local activeHeight = config.activeHeight or (forever and 30 or 26);
    local inactiveHeight = config.inactiveHeight or (forever and 27 or 24);
    local service = self;
    local sideInset = config.sideInset or 6;

    -- the first tab starts right of the portrait ring in the forever style
    local leftInset = config.leftInset or (forever and 48 or sideInset);
    local rightInset = sideInset;
    local arrowSize = 18;

    -- forever style: the header icon buttons of a tabbed window move from
    -- the title bar to the bottom right corner under the content
    if (forever) then
        self:PlaceHeaderButtonsBottom(view);
    end
    local arrowsWidth = arrowSize * 2 + 2 + tabGap;
    local borderColor = { 0.5, 0.5, 0.5, 0.5 };

    local strip = {
        tabs = {},
        activeTab = nil,
        offset = 0,
        totalWidth = 0,
        availableWidth = 0,
        overflow = false,
    };

    -- top border of the content frame: two segments with a gap for the active tab
    local borderTopLeft = contentFrame:CreateTexture(nil, "BORDER");
    borderTopLeft:SetColorTexture(borderColor[1], borderColor[2], borderColor[3], borderColor[4]);
    borderTopLeft:SetHeight(1);
    local borderTopRight = contentFrame:CreateTexture(nil, "BORDER");
    borderTopRight:SetColorTexture(borderColor[1], borderColor[2], borderColor[3], borderColor[4]);
    borderTopRight:SetHeight(1);

    -- clip frame: the visible window of the tab row, the tabs overlap the
    -- content top border by 1px so the active tab merges with the content
    local clipFrame = CreateFrame("Frame", nil, view);
    clipFrame:SetClipsChildren(true);
    clipFrame:SetHeight(activeHeight);
    clipFrame:SetPoint("BOTTOMLEFT", contentFrame, "TOPLEFT", leftInset, -1);
    clipFrame:SetPoint("BOTTOMRIGHT", contentFrame, "TOPRIGHT", -rightInset, -1);
    clipFrame:EnableMouseWheel(true);
    strip.clipFrame = clipFrame;

    -- tab container: holds all tabs side by side, moved left by the scroll offset
    local tabContainer = CreateFrame("Frame", nil, clipFrame);
    tabContainer:SetHeight(activeHeight);
    tabContainer:SetWidth(1);
    tabContainer:SetPoint("BOTTOMLEFT", clipFrame, "BOTTOMLEFT", 0, 0);
    strip.tabContainer = tabContainer;

    -- scroll arrows at the right end of the tab row, only shown on overflow
    local rightArrow = self:CreateFlatSquareButton(view, ">", function()
        strip:ScrollStep(1);
    end, arrowSize);
    rightArrow:SetNormalFontObject("GameFontHighlightSmall");
    rightArrow:SetDisabledFontObject("GameFontDisableSmall");
    rightArrow:SetPoint("BOTTOMRIGHT", contentFrame, "TOPRIGHT", -rightInset, 2);
    rightArrow:Hide();
    local leftArrow = self:CreateFlatSquareButton(view, "<", function()
        strip:ScrollStep(-1);
    end, arrowSize);
    leftArrow:SetNormalFontObject("GameFontHighlightSmall");
    leftArrow:SetDisabledFontObject("GameFontDisableSmall");
    leftArrow:SetPoint("RIGHT", rightArrow, "LEFT", -2, 0);
    leftArrow:Hide();
    strip.leftArrow = leftArrow;
    strip.rightArrow = rightArrow;

    -- Add a tab button at the end of the strip.
    function strip:AddTab(caption, onClick)
        local button = CreateFrame("Button", nil, tabContainer, BackdropTemplateMixin and "BackdropTemplate");
        button:SetBackdrop({
            bgFile = [[Interface/Buttons/WHITE8X8]],
        });
        button:SetBackdropColor(0, 0, 0, 0);
        button:SetNormalFontObject("GameFontNormal");
        button:SetText(caption);
        button:SetWidth(tabWidth);
        button:SetHeight(inactiveHeight);
        button:SetScript("OnClick", onClick);

        -- forever style: tab art of the game ui instead of the flat borders
        if (forever) then
            service:StyleForeverTab(button);
            table.insert(self.tabs, button);
            return button;
        end

        -- left border of tab button
        local tabBorderLeft = button:CreateTexture(nil, "BORDER");
        tabBorderLeft:SetColorTexture(borderColor[1], borderColor[2], borderColor[3], borderColor[4]);
        tabBorderLeft:SetWidth(1);
        tabBorderLeft:SetPoint("TOPLEFT", 0, 0);
        tabBorderLeft:SetPoint("BOTTOMLEFT", 0, 0);

        -- right border of tab button
        local tabBorderRight = button:CreateTexture(nil, "BORDER");
        tabBorderRight:SetColorTexture(borderColor[1], borderColor[2], borderColor[3], borderColor[4]);
        tabBorderRight:SetWidth(1);
        tabBorderRight:SetPoint("TOPRIGHT", 0, 0);
        tabBorderRight:SetPoint("BOTTOMRIGHT", 0, 0);

        -- top border of tab button
        local tabBorderTop = button:CreateTexture(nil, "BORDER");
        tabBorderTop:SetColorTexture(borderColor[1], borderColor[2], borderColor[3], borderColor[4]);
        tabBorderTop:SetHeight(1);
        tabBorderTop:SetPoint("TOPLEFT", 0, 0);
        tabBorderTop:SetPoint("TOPRIGHT", 0, 0);

        -- lens flare on the top edge of the active tab (colors baked into the
        -- texture, drawn additively); optional per addon
        if (config.glowTexture) then
            local activeGlow = button:CreateTexture(nil, "ARTWORK");
            activeGlow:SetTexture(config.glowTexture);
            activeGlow:SetBlendMode("ADD");
            activeGlow:SetAlpha(0.55);
            activeGlow:SetPoint("TOPLEFT", 1, 0);
            activeGlow:SetPoint("TOPRIGHT", -1, 0);
            activeGlow:SetHeight(18);
            activeGlow:Hide();
            button.activeGlow = activeGlow;
        end

        table.insert(self.tabs, button);
        return button;
    end

    -- Show a counter in the addon's purple accent right behind the caption of
    -- a tab (plain text, no background); a count of 0 or nil hides it.
    function strip:SetBadge(button, count)
        local badge = button.badge;
        if (not count or count <= 0) then
            if (badge) then
                badge:Hide();
            end
            return;
        end

        if (not badge) then
            badge = button:CreateFontString(nil, "OVERLAY", "GameFontNormal");
            badge:SetPoint("LEFT", button:GetFontString(), "RIGHT", 4, 0);
            badge:SetTextColor(0.855, 0.549, 1, 1);
            button.badge = badge;
        end

        badge:SetText(count > 99 and "99+" or tostring(count));
        badge:Show();
    end

    -- Measure the visible tabs, place them side by side, decide whether the
    -- arrows are needed and apply the (clamped) scroll offset.
    function strip:Layout()
        -- place visible tabs
        local x = 0;
        for _, tab in ipairs(self.tabs) do
            if (tab:IsShown()) then
                tab.stripX = x;
                tab:ClearAllPoints();
                tab:SetPoint("BOTTOMLEFT", tabContainer, "BOTTOMLEFT", x, 0);
                x = x + tab:GetWidth() + tabGap;
            end
        end
        self.totalWidth = math.max(x - tabGap, 0);
        tabContainer:SetWidth(math.max(self.totalWidth, 1));

        -- a frame that was never laid out reports no width: treat as fitting,
        -- the size change on show lays out again
        local contentWidth = contentFrame:GetWidth() or 0;
        local fullWidth = contentWidth - leftInset - rightInset;
        local overflow = contentWidth > 0 and self.totalWidth > fullWidth;
        if (overflow ~= self.overflow) then
            self.overflow = overflow;
            clipFrame:ClearAllPoints();
            clipFrame:SetPoint("BOTTOMLEFT", contentFrame, "TOPLEFT", leftInset, -1);
            if (overflow) then
                clipFrame:SetPoint("BOTTOMRIGHT", contentFrame, "TOPRIGHT", -(rightInset + arrowsWidth), -1);
                leftArrow:Show();
                rightArrow:Show();
            else
                clipFrame:SetPoint("BOTTOMRIGHT", contentFrame, "TOPRIGHT", -rightInset, -1);
                leftArrow:Hide();
                rightArrow:Hide();
            end
        end
        if (overflow) then
            self.availableWidth = fullWidth - arrowsWidth;
        else
            self.availableWidth = math.max(fullWidth, self.totalWidth);
        end

        self:ApplyOffset();
    end

    -- Clamp the scroll offset, move the tab container, update the arrows and
    -- the border gap.
    function strip:ApplyOffset()
        local maxOffset = math.max(self.totalWidth - self.availableWidth, 0);
        self.offset = math.min(math.max(self.offset, 0), maxOffset);
        tabContainer:SetPoint("BOTTOMLEFT", clipFrame, "BOTTOMLEFT", -self.offset, 0);

        -- arrows: dim the one that cannot scroll further
        local function SetArrowEnabled(arrow, enabled)
            arrow:SetEnabled(enabled);
            arrow:SetAlpha(enabled and 1 or 0.6);
        end
        SetArrowEnabled(leftArrow, self.offset > 0);
        SetArrowEnabled(rightArrow, self.offset < maxOffset);

        self:UpdateBorder();
    end

    -- Draw the content top border with a gap under the visible part of the
    -- active tab (no gap when the active tab is scrolled out of view).
    function strip:UpdateBorder()
        local contentWidth = contentFrame:GetWidth() or 0;
        local gapLeft, gapRight = 0, 0;
        local active = self.activeTab;
        if (active and active:IsShown() and active.stripX) then
            local visibleLeft = leftInset;
            local visibleRight = leftInset + self.availableWidth;
            local tabLeft = leftInset + active.stripX - self.offset;
            local tabRight = tabLeft + active:GetWidth();
            gapLeft = math.min(math.max(tabLeft, visibleLeft), visibleRight);
            gapRight = math.min(math.max(tabRight, visibleLeft), visibleRight);
        end

        borderTopLeft:ClearAllPoints();
        borderTopRight:ClearAllPoints();
        if (gapRight <= gapLeft) then
            -- no gap: one full line
            borderTopLeft:SetPoint("TOPLEFT", contentFrame, "TOPLEFT", 0, 0);
            borderTopLeft:SetPoint("TOPRIGHT", contentFrame, "TOPRIGHT", 0, 0);
            borderTopLeft:Show();
            borderTopRight:Hide();
            return;
        end

        -- left segment up to the gap
        if (gapLeft > 0) then
            borderTopLeft:SetPoint("TOPLEFT", contentFrame, "TOPLEFT", 0, 0);
            borderTopLeft:SetWidth(gapLeft);
            borderTopLeft:Show();
        else
            borderTopLeft:Hide();
        end

        -- right segment from the gap to the edge
        if (gapRight < contentWidth) then
            borderTopRight:SetPoint("TOPLEFT", contentFrame, "TOPLEFT", gapRight, 0);
            borderTopRight:SetPoint("TOPRIGHT", contentFrame, "TOPRIGHT", 0, 0);
            borderTopRight:Show();
        else
            borderTopRight:Hide();
        end
    end

    -- Scroll so the given tab is fully visible.
    function strip:ScrollToTab(tab)
        if (not tab or not tab.stripX or not tab:IsShown()) then
            return;
        end
        if (tab.stripX < self.offset) then
            self.offset = tab.stripX;
        elseif (tab.stripX + tab:GetWidth() > self.offset + self.availableWidth) then
            self.offset = tab.stripX + tab:GetWidth() - self.availableWidth;
        end
        self:ApplyOffset();
    end

    -- Scroll one tab to the left (-1) or right (1), aligned to tab starts.
    function strip:ScrollStep(direction)
        local target = nil;
        for _, tab in ipairs(self.tabs) do
            if (tab:IsShown() and tab.stripX) then
                if (direction < 0 and tab.stripX < self.offset) then
                    target = tab.stripX;
                elseif (direction > 0 and tab.stripX > self.offset and target == nil) then
                    target = tab.stripX;
                end
            end
        end
        if (target ~= nil) then
            self.offset = target;
            self:ApplyOffset();
        end
    end

    -- Mark a tab as active (nil = none), lay out and bring it into view.
    function strip:SetActive(activeButton)
        self.activeTab = activeButton;
        for _, tab in ipairs(self.tabs) do
            local fontString = tab:GetFontString();
            local isActive = (tab == activeButton);
            tab:SetHeight(isActive and activeHeight or inactiveHeight);
            if (forever) then
                service:SetForeverTabActive(tab, isActive);
            elseif (isActive) then
                tab:SetBackdropColor(0, 0, 0, 0.5);
                fontString:SetTextColor(1, 0.84, 0, 1);
                if (tab.activeGlow) then tab.activeGlow:Show(); end
            else
                tab:SetBackdropColor(0, 0, 0, 0);
                fontString:SetTextColor(1, 1, 1, 1);
                if (tab.activeGlow) then tab.activeGlow:Hide(); end
            end
        end
        self:Layout();
        self:ScrollToTab(activeButton);
    end

    -- re-layout when the strip width changes (window resize) and scroll with
    -- the mouse wheel over the tabs
    clipFrame:SetScript("OnSizeChanged", function()
        strip:Layout();
    end);
    clipFrame:SetScript("OnMouseWheel", function(_, delta)
        if (strip.overflow) then
            strip:ScrollStep(delta > 0 and -1 or 1);
        end
    end);

    strip:UpdateBorder();
    return strip;
end

--- Attach a purple hover glow to a frame: 1px border on all edges plus a
-- subtle purple backdrop, shown while the mouse is over the frame.
-- @param frame Frame to decorate (mouse enabled).
-- @param extraHoverRegions Optional mouse-enabled child frames (e.g. column
-- hover regions of a list row) that also keep the glow alive.
-- Set frame.hoverGlowDisabled = true to suppress the glow (e.g. rows without
-- any click action).
function UiService:AttachHoverGlow(frame, extraHoverRegions)
    -- forever style: the yellow row hover of the profession window
    if (self:IsForever()) then
        self:AttachForeverRowHover(frame, extraHoverRegions);
        return;
    end
    local color = self.HoverBorderColor;
    local regions = {};

    -- 1px border on all four edges
    local function CreateEdge()
        local edge = frame:CreateTexture(nil, "BORDER");
        edge:SetColorTexture(color[1], color[2], color[3], color[4]);
        edge:Hide();
        table.insert(regions, edge);
        return edge;
    end
    local topEdge = CreateEdge();
    topEdge:SetHeight(1);
    topEdge:SetPoint("TOPLEFT", 0, 0);
    topEdge:SetPoint("TOPRIGHT", 0, 0);
    local bottomEdge = CreateEdge();
    bottomEdge:SetHeight(1);
    bottomEdge:SetPoint("BOTTOMLEFT", 0, 0);
    bottomEdge:SetPoint("BOTTOMRIGHT", 0, 0);
    local leftEdge = CreateEdge();
    leftEdge:SetWidth(1);
    leftEdge:SetPoint("TOPLEFT", 0, 0);
    leftEdge:SetPoint("BOTTOMLEFT", 0, 0);
    local rightEdge = CreateEdge();
    rightEdge:SetWidth(1);
    rightEdge:SetPoint("TOPRIGHT", 0, 0);
    rightEdge:SetPoint("BOTTOMRIGHT", 0, 0);

    -- toggle all glow textures at once
    local function SetGlowShown(shown)
        for _, region in ipairs(regions) do
            region:SetShown(shown);
        end
    end

    -- keep the glow while the mouse is anywhere over the frame; hooked so the
    -- existing hover handlers keep working; runs after them and replaces their
    -- gray hover backdrop with the subtle purple one
    local backdropColor = self.HoverBackdropColor;
    local function OnGlowEnter()
        -- frames can opt out of the hover glow (e.g. non-clickable rows)
        if (frame.hoverGlowDisabled) then
            return;
        end
        SetGlowShown(true);
        if (frame.SetBackdropColor) then
            frame:SetBackdropColor(backdropColor[1], backdropColor[2], backdropColor[3], backdropColor[4]);
        end
    end
    local function OnGlowLeave()
        if (frame:IsMouseOver()) then return; end
        SetGlowShown(false);
    end

    -- expose for hover regions created later (e.g. pooled labels inside the
    -- row); hoverGlowHide resets unconditionally — needed when a dialog opens
    -- under the mouse and the row never receives a leave event
    frame.hoverGlowEnter = OnGlowEnter;
    frame.hoverGlowLeave = OnGlowLeave;
    frame.hoverGlowHide = function()
        SetGlowShown(false);
    end;

    frame:HookScript("OnEnter", OnGlowEnter);
    frame:HookScript("OnLeave", OnGlowLeave);
    frame:HookScript("OnHide", function() SetGlowShown(false); end);
    if (extraHoverRegions) then
        for _, region in ipairs(extraHoverRegions) do
            region:HookScript("OnEnter", OnGlowEnter);
            region:HookScript("OnLeave", OnGlowLeave);

            -- a region hidden while the mouse is over it never fires OnLeave,
            -- which would leave the glow stuck on the row
            region:HookScript("OnHide", OnGlowLeave);
        end
    end
end

--- Create edit box with dark flat styling.
-- @param container Parent frame.
-- @param width Width in pixels.
-- @return Container frame with .editBox (the EditBox) and :GetText() / :SetText() helpers.
function UiService:CreateEditBox(container, width)
    local frame = CreateFrame("Frame", nil, container, BackdropTemplateMixin and "BackdropTemplate");
    frame:SetBackdrop({
        bgFile = [[Interface/Buttons/WHITE8X8]],
        edgeFile = [[Interface/Buttons/WHITE8X8]],
        edgeSize = 1
    });
    local forever = self:IsForever();
    if (forever) then
        -- dark inset field of the game ui, the backdrop stays invisible
        frame:SetBackdropColor(0, 0, 0, 0);
        frame:SetBackdropBorderColor(0, 0, 0, 0);
        self:CreateForeverFieldArt(frame);
    else
        frame:SetBackdropColor(0.12, 0.12, 0.12, 0.95);
        frame:SetBackdropBorderColor(0.3, 0.3, 0.3, 0.45);
    end
    frame:SetWidth(width);
    frame:SetHeight(22);

    local editBox = CreateFrame("EditBox", nil, frame);
    editBox:SetFontObject("ChatFontNormal");
    editBox:SetPoint("TOPLEFT", forever and 8 or 6, -3);
    editBox:SetPoint("BOTTOMRIGHT", forever and -8 or -6, 3);
    editBox:SetAutoFocus(false);
    frame.editBox = editBox;

    -- hover and focus feedback: purple border (classic) or brighter field art (forever)
    local service = self;
    local hoverColor = self.HoverBorderColor;
    local focusColor = self.HoverBorderFocusColor;
    local function SetState(active, focused)
        if (forever) then
            service:SetForeverFieldActive(frame, active or focused);
        elseif (focused) then
            frame:SetBackdropBorderColor(focusColor[1], focusColor[2], focusColor[3], focusColor[4]);
        elseif (active) then
            frame:SetBackdropBorderColor(hoverColor[1], hoverColor[2], hoverColor[3], hoverColor[4]);
        else
            frame:SetBackdropBorderColor(0.3, 0.3, 0.3, 0.45);
        end
    end
    frame:SetScript("OnEnter", function()
        SetState(true, editBox:HasFocus());
    end);
    frame:SetScript("OnLeave", function()
        SetState(false, editBox:HasFocus());
    end);
    editBox:SetScript("OnEditFocusGained", function()
        SetState(false, true);
    end);
    editBox:SetScript("OnEditFocusLost", function()
        SetState(false, false);
    end);

    -- convenience helpers
    function frame:GetText()
        return editBox:GetText();
    end
    function frame:SetText(text)
        editBox:SetText(text or "");
    end
    function frame:SetPlaceholder(text)
        if (not self.placeholder) then
            local placeholder = frame:CreateFontString(nil, "ARTWORK", "GameFontDisableSmall");
            placeholder:SetPoint("LEFT", 6, 0);
            self.placeholder = placeholder;
            editBox:HookScript("OnTextChanged", function()
                placeholder:SetShown(editBox:GetText() == "");
            end);
            editBox:HookScript("OnEditFocusGained", function()
                placeholder:Hide();
            end);
            editBox:HookScript("OnEditFocusLost", function()
                placeholder:SetShown(editBox:GetText() == "");
            end);
        end
        self.placeholder:SetText(text);
        self.placeholder:SetShown(editBox:GetText() == "");
    end

    return frame;
end

--- Create number edit box (right-aligned text).
-- @param container Parent frame.
-- @param width Width in pixels.
function UiService:CreateNumberEditBox(container, width)
    local frame = self:CreateEditBox(container, width);
    frame.editBox:SetJustifyH("RIGHT");
    return frame;
end

-- registry of all dropdown instances for mutual close behavior
UiService.openDropdowns = UiService.openDropdowns or {};

--- Close all open dropdowns except the given one.
function UiService:CloseOtherDropdowns(exceptFrame)
    for _, dropdown in ipairs(self.openDropdowns) do
        if (dropdown ~= exceptFrame and dropdown.menuFrame and dropdown.menuFrame:IsShown()) then
            dropdown.menuFrame:Hide();
        end
    end
end

-- round marker texture of dropdown items with a dot (tinted per item)
local DropdownDotTexture = "Interface\\CharacterFrame\\TempPortraitAlphaMask";

--- Create the round marker texture of a dropdown row or label.
-- @param parent Frame the texture belongs to.
-- @param rightOffset Distance of the dot from the right edge.
local function CreateDropdownDot(parent, rightOffset)
    local dot = parent:CreateTexture(nil, "OVERLAY");
    dot:SetSize(6, 6);
    dot:SetPoint("RIGHT", -rightOffset, 0);
    dot:SetTexture(DropdownDotTexture);
    dot:Hide();
    return dot;
end

--- Show the dot of an item in its color and keep the text clear of it.
-- @param dot Texture from CreateDropdownDot.
-- @param text FontString left of the dot.
-- @param item Dropdown item (dot = { r, g, b } or nil).
-- @param textRight Right inset of the text without a dot.
local function ApplyDropdownDot(dot, text, item, textRight)
    local color = item and item.dot;
    if (color) then
        dot:SetVertexColor(color[1], color[2], color[3]);
        dot:Show();
        text:SetPoint("RIGHT", -(textRight + 12), 0);
    else
        dot:Hide();
        text:SetPoint("RIGHT", -textRight, 0);
    end
end

--- Create dropdown with dark flat styling.
-- @param container Parent frame.
-- @param width Width in pixels.
-- @param items Table of items: { { value = ..., text = "...", dot = { r, g, b } or nil, tooltip = "..." or nil }, ... }; a dot draws a small round marker at the right end of the row and of the selected label, a tooltip shows beside the menu row while it is hovered (title: the item text).
-- @param onSelect Callback function(value, text) called when an item is selected.
-- @return Dropdown frame with :SetValue(value), :GetValue(), :SetItems(items).
function UiService:CreateDropdown(container, width, items, onSelect)
    local frame = CreateFrame("Frame", nil, container, BackdropTemplateMixin and "BackdropTemplate");
    frame:SetBackdrop({
        bgFile = [[Interface/Buttons/WHITE8X8]],
        edgeFile = [[Interface/Buttons/WHITE8X8]],
        edgeSize = 1
    });
    local forever = self:IsForever();
    local service = self;
    if (forever) then
        -- dark inset field with the red arrow button of the game ui
        frame:SetBackdropColor(0, 0, 0, 0);
        frame:SetBackdropBorderColor(0, 0, 0, 0);
        self:CreateForeverFieldArt(frame);
    else
        frame:SetBackdropColor(0.12, 0.12, 0.12, 0.95);
        frame:SetBackdropBorderColor(0.3, 0.3, 0.3, 0.45);
    end
    frame:SetWidth(width);
    frame:SetHeight(22);

    -- selected text label with the dot of the selected item left of the arrow
    local labelRight = forever and 26 or 18;
    local label = frame:CreateFontString(nil, "OVERLAY", "GameFontHighlightSmall");
    label:SetPoint("LEFT", forever and 8 or 6, 0);
    label:SetPoint("RIGHT", -labelRight, 0);
    label:SetJustifyH("LEFT");
    frame.label = label;
    local labelDot = CreateDropdownDot(frame, labelRight);
    local function SetLabel(item)
        label:SetText(item and item.text or "");
        ApplyDropdownDot(labelDot, label, item, labelRight);
    end

    -- arrow indicator
    local arrow;
    if (forever) then
        arrow = self:CreateForeverDropdownArrow(frame);
    else
        arrow = frame:CreateTexture(nil, "OVERLAY");
        arrow:SetSize(8, 8);
        arrow:SetPoint("RIGHT", -6, 0);
        arrow:SetTexture([[Interface\Buttons\UI-ScrollBar-ScrollDownButton-Up]]);
        arrow:SetTexCoord(0.25, 0.75, 0.25, 0.75);
        arrow:SetVertexColor(0.8, 0.8, 0.8);
    end

    -- state
    frame.items = items or {};
    frame.selectedValue = nil;
    frame.onSelect = onSelect;
    frame.menuFrame = nil;

    -- hover highlight: purple border (classic) or brighter field and arrow (forever)
    local hoverColor = self.HoverBorderColor;
    local function IsMenuOpen()
        return frame.menuFrame and frame.menuFrame:IsShown();
    end
    local function SetHover(active)
        if (forever) then
            service:SetForeverFieldActive(frame, active or IsMenuOpen());
            arrow:SetState(IsMenuOpen() and "open" or (active and "hover" or "normal"));
        elseif (active) then
            frame:SetBackdropBorderColor(hoverColor[1], hoverColor[2], hoverColor[3], hoverColor[4]);
        else
            frame:SetBackdropBorderColor(0.3, 0.3, 0.3, 0.45);
        end
    end
    frame:SetScript("OnEnter", function()
        SetHover(true);
    end);
    frame:SetScript("OnLeave", function()
        SetHover(false);
    end);

    -- close menu helper
    local function CloseMenu()
        if (frame.menuFrame and frame.menuFrame:IsShown()) then
            frame.menuFrame:Hide();
        end
        SetHover(frame:IsMouseOver());
    end

    -- register in dropdown list
    table.insert(UiService.openDropdowns, frame);

    -- build and show menu
    local function ShowMenu()
        if (frame.menuFrame and frame.menuFrame:IsShown()) then
            CloseMenu();
            return;
        end

        -- close any other open dropdown
        UiService:CloseOtherDropdowns(frame);

        if (not frame.menuFrame) then
            local menu = CreateFrame("Frame", nil, frame, BackdropTemplateMixin and "BackdropTemplate");
            menu:SetBackdrop({
                bgFile = [[Interface/Buttons/WHITE8X8]],
                edgeFile = [[Interface/Buttons/WHITE8X8]],
                edgeSize = 1
            });
            menu:SetBackdropColor(0.1, 0.1, 0.1, 0.97);
            menu:SetBackdropBorderColor(0.4, 0.4, 0.4, 0.6);
            if (forever) then
                service:StyleForeverMenu(menu);
            end
            menu:SetFrameStrata("FULLSCREEN_DIALOG");
            menu:SetClampedToScreen(true);
            menu:Hide();
            frame.menuFrame = menu;
        end

        local menu = frame.menuFrame;

        -- clear old rows
        if (menu.rows) then
            for _, row in ipairs(menu.rows) do
                row:Hide();
            end
        end
        menu.rows = {};

        -- the rounded menu art needs room around the rows: the insets of the
        -- game menus, more at the bottom where the art has its shadow; the art
        -- reaches 3px above the menu, so the menu starts a little lower
        local rowHeight = forever and 20 or 18;
        local paddingSide = forever and 8 or 1;
        local paddingTop = forever and 8 or 2;
        local paddingBottom = forever and 15 or 2;
        local menuWidth = width;
        local itemCount = #frame.items;
        local menuHeight = itemCount * rowHeight + paddingTop + paddingBottom;
        menu:SetWidth(menuWidth);
        menu:SetHeight(menuHeight);
        menu:ClearAllPoints();
        menu:SetPoint("TOPLEFT", frame, "BOTTOMLEFT", 0, forever and -4 or -1);

        -- row colors: gray (classic) or a soft gold (forever)
        local selectedColor = forever and { 1, 0.82, 0, 0.18 } or { 0.2, 0.2, 0.2, 0.8 };
        local hoverRowColor = forever and { 1, 0.82, 0, 0.3 } or { 0.25, 0.25, 0.25, 0.9 };

        for index, item in ipairs(frame.items) do
            local row = CreateFrame("Button", nil, menu, BackdropTemplateMixin and "BackdropTemplate");
            row:SetHeight(rowHeight);
            row:SetPoint("TOPLEFT", paddingSide, -(paddingTop + (index - 1) * rowHeight));
            row:SetPoint("TOPRIGHT", -paddingSide, -(paddingTop + (index - 1) * rowHeight));
            row:SetBackdrop({
                bgFile = [[Interface/Buttons/WHITE8X8]]
            });
            row:SetBackdropColor(0, 0, 0, 0);

            local rowLabel = row:CreateFontString(nil, "OVERLAY", "GameFontHighlightSmall");
            rowLabel:SetPoint("LEFT", forever and 8 or 5, 0);
            rowLabel:SetPoint("RIGHT", -5, 0);
            rowLabel:SetJustifyH("LEFT");
            rowLabel:SetText(item.text);
            ApplyDropdownDot(CreateDropdownDot(row, 6), rowLabel, item, 5);

            -- highlight selected item
            if (item.value == frame.selectedValue) then
                row:SetBackdropColor(selectedColor[1], selectedColor[2], selectedColor[3], selectedColor[4]);
            end

            row:SetScript("OnEnter", function(self)
                self:SetBackdropColor(hoverRowColor[1], hoverRowColor[2], hoverRowColor[3], hoverRowColor[4]);

                -- optional explanation of the item beside the menu
                if (item.tooltip) then
                    GameTooltip:SetOwner(self, "ANCHOR_RIGHT");
                    GameTooltip:AddLine(item.text);
                    GameTooltip:AddLine(item.tooltip, 1, 1, 1, true);
                    GameTooltip:Show();
                end
            end);
            row:SetScript("OnLeave", function(self)
                if (item.value == frame.selectedValue) then
                    self:SetBackdropColor(selectedColor[1], selectedColor[2], selectedColor[3], selectedColor[4]);
                else
                    self:SetBackdropColor(0, 0, 0, 0);
                end
                if (item.tooltip) then
                    GameTooltip:Hide();
                end
            end);
            row:SetScript("OnClick", function()
                -- the closing menu hides the row without a leave event
                if (item.tooltip) then
                    GameTooltip:Hide();
                end
                frame.selectedValue = item.value;
                SetLabel(item);
                CloseMenu();
                if (frame.onSelect) then
                    frame.onSelect(item.value, item.text);
                end
            end);
            table.insert(menu.rows, row);
        end

        menu:Show();
        SetHover(true);
    end

    -- click to toggle menu
    frame:EnableMouse(true);
    frame:SetScript("OnMouseDown", function()
        ShowMenu();
    end);

    -- close menu when clicking elsewhere
    frame:SetScript("OnHide", function()
        CloseMenu();
    end);

    -- public API
    function frame:SetValue(value)
        self.selectedValue = value;
        for _, item in ipairs(self.items) do
            if (item.value == value) then
                SetLabel(item);
                return;
            end
        end
        SetLabel(nil);
    end

    function frame:GetValue()
        return self.selectedValue;
    end

    function frame:SetItems(newItems)
        self.items = newItems or {};
    end

    -- set initial display
    if (#frame.items > 0) then
        SetLabel(frame.items[1]);
        frame.selectedValue = frame.items[1].value;
    end

    return frame;
end

