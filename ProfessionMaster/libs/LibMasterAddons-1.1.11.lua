-- create frame
function UiService:CreateView(name, width, height, title, showShortcut, resizable, minWidth, minHeight, resizeDirections)
    -- create view; parented to UIParent so the window follows the game ui
    -- (hidden with Alt+Z, in cinematics and in the afk mode of ui packs like ElvUI)
    local view = CreateFrame("Frame", nil, UIParent, BackdropTemplateMixin and "BackdropTemplate");
    view:SetFrameStrata("HIGH");
    view:SetWidth(width);
    view:SetHeight(height);
    view.ownerAddon = self.addon;
    view.positionName = name;
    view.defaultWidth = width;
    view.defaultHeight = height;
    view.minWidth = minWidth or math.floor(width * 0.67);
    view.minHeight = minHeight or math.floor(height * 0.6);
    view:SetFrameLevel(currentZIndex);
    view:SetBackdrop({
        bgFile = [[Interface/Buttons/WHITE8X8]],
    });
    view:SetBackdropColor(0, 0, 0, 0.8);
    currentZIndex = currentZIndex + 20;

    -- gradient border: purple (top-left) to gold (bottom-right)
    local purpleColor = { 0.6, 0.3, 0.9 };
    local goldColor = { 0.95, 0.65, 0.15 };

    -- corners: TL=purple, BR=gold, TR=80% gold + 20% purple, BL=80% purple + 20% gold
    local function MixColors(c1, c2, t)
        return { c1[1] + (c2[1] - c1[1]) * t, c1[2] + (c2[2] - c1[2]) * t, c1[3] + (c2[3] - c1[3]) * t };
    end
    local cornerTL = purpleColor;
    local cornerTR = MixColors(purpleColor, goldColor, 0.8);
    local cornerBL = MixColors(purpleColor, goldColor, 0.2);
    local cornerBR = goldColor;

    -- create 4 border textures with gradients
    local function SetBorderGradient(tex, orientation, c1, c2)
        if (tex.SetGradientAlpha) then
            tex:SetGradientAlpha(orientation, c1[1], c1[2], c1[3], 1, c2[1], c2[2], c2[3], 1);
        else
            tex:SetGradient(orientation, CreateColor(c1[1], c1[2], c1[3], 1), CreateColor(c2[1], c2[2], c2[3], 1));
        end
    end

    local borderTop = view:CreateTexture(nil, "BORDER");
    borderTop:SetTexture([[Interface\Buttons\WHITE8x8]]);
    borderTop:SetHeight(1);
    borderTop:SetPoint("TOPLEFT", view, "TOPLEFT", 0, 0);
    borderTop:SetPoint("TOPRIGHT", view, "TOPRIGHT", 0, 0);
    SetBorderGradient(borderTop, "HORIZONTAL", cornerTL, cornerTR);
    borderTop:SetAlpha(0);
    borderTop:Hide();

    local borderBottom = view:CreateTexture(nil, "BORDER");
    borderBottom:SetTexture([[Interface\Buttons\WHITE8x8]]);
    borderBottom:SetHeight(1);
    borderBottom:SetPoint("BOTTOMLEFT", view, "BOTTOMLEFT", 0, 0);
    borderBottom:SetPoint("BOTTOMRIGHT", view, "BOTTOMRIGHT", 0, 0);
    SetBorderGradient(borderBottom, "HORIZONTAL", cornerBL, cornerBR);
    borderBottom:SetAlpha(0);
    borderBottom:Hide();

    local borderLeft = view:CreateTexture(nil, "BORDER");
    borderLeft:SetTexture([[Interface\Buttons\WHITE8x8]]);
    borderLeft:SetWidth(1);
    borderLeft:SetPoint("TOPLEFT", view, "TOPLEFT", 0, 0);
    borderLeft:SetPoint("BOTTOMLEFT", view, "BOTTOMLEFT", 0, 0);
    SetBorderGradient(borderLeft, "VERTICAL", cornerBL, cornerTL);
    borderLeft:SetAlpha(0);
    borderLeft:Hide();

    local borderRight = view:CreateTexture(nil, "BORDER");
    borderRight:SetTexture([[Interface\Buttons\WHITE8x8]]);
    borderRight:SetWidth(1);
    borderRight:SetPoint("TOPRIGHT", view, "TOPRIGHT", 0, 0);
    borderRight:SetPoint("BOTTOMRIGHT", view, "BOTTOMRIGHT", 0, 0);
    SetBorderGradient(borderRight, "VERTICAL", cornerBR, cornerTR);
    borderRight:SetAlpha(0);
    borderRight:Hide();

    local borderTextures = { borderTop, borderBottom, borderLeft, borderRight };

    -- border hover fade effect
    local borderFadeDuration = 0.2;
    local borderFadeDirection = 0; -- 0=idle, 1=fading in, -1=fading out
    local borderProgress = 0;
    local borderMaxAlpha = 0.8;
    local borderShouldShow = false;

    -- store border control on view so resize/drag hooks can access it
    view.borderShow = function()
        if (borderShouldShow) then return; end
        borderShouldShow = true;
        borderFadeDirection = 1;
        for _, tex in ipairs(borderTextures) do
            tex:Show();
        end
    end;
    view.borderHide = function()
        if (not borderShouldShow) then return; end
        borderShouldShow = false;
        borderFadeDirection = -1;
    end;

    view:HookScript("OnUpdate", function(_, dt)
        if (borderFadeDirection == 0) then return; end
        borderProgress = borderProgress + (borderFadeDirection * dt / borderFadeDuration);
        if (borderProgress >= 1) then
            borderProgress = 1;
            borderFadeDirection = 0;
        elseif (borderProgress <= 0) then
            borderProgress = 0;
            borderFadeDirection = 0;
            for _, tex in ipairs(borderTextures) do
                tex:Hide();
            end
        end
        local alpha = borderProgress * borderMaxAlpha;
        for _, tex in ipairs(borderTextures) do
            tex:SetAlpha(alpha);
        end
    end);

    -- absolute window scale of the Master addons (see Lib:GetUiScale), the ui
    -- scale of the game is factored out so the window keeps its size under
    -- UIParent; the window follows later changes of the scale
    view:SetScale(Lib:GetUiScale() / UIParent:GetScale());
    Lib.scaledViews[view] = true;

    -- the window holding the scale slider keeps its scale while it is open,
    -- it takes the new one when it is closed and so opens with it next time
    view:HookScript("OnHide", function()
        view:SetScale(Lib:GetUiScale() / UIParent:GetScale());
    end);

    -- add title
    local titleLabel = view:CreateFontString(nil, "OVERLAY", "GameFontNormalLeft");
    titleLabel:SetPoint("TOPLEFT", 16, -14);
    local titleText = title or "";
    if (showShortcut ~= false) then
        titleText = self.addon.shortcut .. titleText;
    end
    titleLabel:SetText(titleText);
    view.titleLabel = titleLabel;

    -- forever style: opaque rock background under the metal frame, the
    -- gradient border and its drag fade stay off (tool windows: plain corner
    -- instead of the portrait ring, see CreateToolView)
    if (self:IsForever()) then
        view:SetBackdropColor(0, 0, 0, 0);
        view.borderShow = function() end;
        view.borderHide = function() end;
        self:CreateForeverWindowArt(view, self.creatingToolView, self.creatingOverlayView);
    end

    -- set moveable
    view:SetMovable(true);
    view:EnableMouse(true);
    view:SetClampedToScreen(true);
    view:RegisterForDrag("LeftButton");

    -- restore position and size
    self:RestorePosition(view);
    self:RestoreSize(view, width, height);

    -- validate that view is visible on screen
    self:ValidateOnScreen(view);

    -- set up resizable behavior
    if (resizable) then
        self:SetupResizable(view, resizeDirections);
    end

    -- set drag handlers (only start drag if not on edge)
    local service = self;
    view:SetScript("OnDragStart", function()
        -- skip if another window is already being dragged or resized
        if (isInteracting) then return; end
        if (not view.amResizing) then
            isInteracting = true;
            view.amMoving = true;
            view:StartMoving();
            view.borderShow();
        end
    end);
    view:SetScript("OnDragStop", function()
        view:StopMovingOrSizing();
        isInteracting = false;
        view.amMoving = false;
        service:StorePosition(view);
        view.borderHide();
    end);

    -- a view hidden while it is dragged gets no OnDragStop, which would
    -- leave the global flag set and block all other windows
    view:HookScript("OnHide", function()
        if (view.amMoving) then
            view:StopMovingOrSizing();
            isInteracting = false;
            view.amMoving = false;
            service:StorePosition(view);
            view.borderHide();
        end
    end);

    -- enforce minimum size at runtime
    view:HookScript("OnSizeChanged", function(self, newWidth, newHeight)
        local enforced = false;
        if (newWidth < self.minWidth) then
            self:SetWidth(self.minWidth);
            enforced = true;
        end
        if (newHeight < self.minHeight) then
            self:SetHeight(self.minHeight);
            enforced = true;
        end
        if (enforced) then
            service:StoreSize(self);
        end
    end);

    -- method to update min size at runtime
    view.SetMinSize = function(self, newMinWidth, newMinHeight)
        self.minWidth = newMinWidth;
        self.minHeight = newMinHeight;
        self:SetResizeBounds(newMinWidth, newMinHeight);

        -- enforce immediately
        if (self:GetWidth() < newMinWidth) then
            self:SetWidth(newMinWidth);
        end
        if (self:GetHeight() < newMinHeight) then
            self:SetHeight(newMinHeight);
        end
    end;

    return view;
end

--- Show the custom resize cursor frame at the mouse position.
-- @param texture Cursor texture path.
-- @param rotation Rotation in degrees.
function UiService:ShowResizeCursor(texture, rotation)
    if (not self.resizeCursorFrame) then
        local frame = CreateFrame("Frame", nil, UIParent);
        frame:Hide();
        frame:SetSize(24, 24);
        frame:SetFrameStrata("TOOLTIP");
        frame.texture = frame:CreateTexture();
        frame.texture:SetAllPoints();
        frame:SetScript("OnUpdate", function(cursorFrame)
            local cursorX, cursorY = GetCursorPosition();
            local scale = cursorFrame:GetEffectiveScale();
            cursorFrame:SetPoint("CENTER", UIParent, "BOTTOMLEFT", cursorX / scale, cursorY / scale);
        end);
        self.resizeCursorFrame = frame;
    end
    self.resizeCursorFrame.texture:SetTexture(texture);
    self.resizeCursorFrame.texture:SetRotation(math.rad(rotation), { x = 0.5, y = 0.5 });

    -- set initial position immediately so the frame is visible on the first render
    local cursorX, cursorY = GetCursorPosition();
    local scale = self.resizeCursorFrame:GetEffectiveScale();
    self.resizeCursorFrame:ClearAllPoints();
    self.resizeCursorFrame:SetPoint("CENTER", UIParent, "BOTTOMLEFT", cursorX / scale, cursorY / scale);
    self.resizeCursorFrame:Show();
end

--- Hide the custom resize cursor frame.
function UiService:HideResizeCursor()
    if (self.resizeCursorFrame) then
        self.resizeCursorFrame:Hide();
    end
end

--- Set up resizable behavior on a view frame.
-- @param view The frame to make resizable.
-- @param resizeDirections Optional table of allowed resize directions.
function UiService:SetupResizable(view, resizeDirections)
    local service = self;
    view:SetResizable(true);
    view:SetResizeBounds(view.minWidth, view.minHeight);

    local edgeSize = 6;
    local resizeDirection = nil;
    view.amResizing = false;
    local currentCursor = nil;
    local allowedDirections = nil;

    if (type(resizeDirections) == "table") then
        allowedDirections = {};
        for key, value in pairs(resizeDirections) do
            if (type(key) == "number") then
                allowedDirections[value] = true;
            elseif (value) then
                allowedDirections[key] = true;
            end
        end
    end

    local function IsResizeDirectionAllowed(direction)
        return not allowedDirections or allowedDirections[direction];
    end

    local function FirstAllowedDirection(...)
        for i = 1, select("#", ...) do
            local direction = select(i, ...);
            if (IsResizeDirectionAllowed(direction)) then
                return direction;
            end
        end
        return nil;
    end

    -- map resize directions to cursor texture and rotation (in degrees)
    local directionCursors = {
        TOPLEFT     = { texture = [[Interface\CURSOR\UI-Cursor-SizeRight]],  rotation = 0  },
        BOTTOMRIGHT = { texture = [[Interface\CURSOR\UI-Cursor-SizeRight]],  rotation = 0  },
        TOPRIGHT    = { texture = [[Interface\CURSOR\UI-Cursor-SizeLeft]],   rotation = 0  },
        BOTTOMLEFT  = { texture = [[Interface\CURSOR\UI-Cursor-SizeLeft]],   rotation = 0  },
        TOP         = { texture = [[Interface\CURSOR\UI-Cursor-SizeLeft]],   rotation = 45 },
        BOTTOM      = { texture = [[Interface\CURSOR\UI-Cursor-SizeLeft]],   rotation = 45 },
        LEFT        = { texture = [[Interface\CURSOR\UI-Cursor-SizeRight]],  rotation = 45 },
        RIGHT       = { texture = [[Interface\CURSOR\UI-Cursor-SizeRight]],  rotation = 45 },
    };

    local function UpdateResizeCursor(direction)
        if (direction == currentCursor) then return; end
        currentCursor = direction;
        if (direction) then
            local cursorInfo = directionCursors[direction];
            service:ShowResizeCursor(cursorInfo.texture, cursorInfo.rotation);
            view.borderShow();
        else
            service:HideResizeCursor();
            if (not view.amResizing) then
                view.borderHide();
            end
        end
    end

    local function GetResizeDirection()
        -- only detect edges when mouse is over the frame
        if (not view:IsMouseOver()) then return nil; end

        local x, y = GetCursorPosition();
        local scale = view:GetEffectiveScale();
        x, y = x / scale, y / scale;
        local left = view:GetLeft();
        local right = view:GetRight();
        local top = view:GetTop();
        local bottom = view:GetBottom();
        if (not left) then return nil; end

        local atLeft = (x - left) < edgeSize;
        local atRight = (right - x) < edgeSize;
        local atTop = (top - y) < edgeSize;
        local atBottom = (y - bottom) < edgeSize;

        if (atTop and atLeft) then return FirstAllowedDirection("TOPLEFT", "TOP", "LEFT"); end
        if (atTop and atRight) then return FirstAllowedDirection("TOPRIGHT", "TOP", "RIGHT"); end
        if (atBottom and atLeft) then return FirstAllowedDirection("BOTTOMLEFT", "BOTTOM", "LEFT"); end
        if (atBottom and atRight) then return FirstAllowedDirection("BOTTOMRIGHT", "BOTTOM", "RIGHT"); end
        if (atTop) then return FirstAllowedDirection("TOP"); end
        if (atBottom) then return FirstAllowedDirection("BOTTOM"); end
        if (atLeft) then return FirstAllowedDirection("LEFT"); end
        if (atRight) then return FirstAllowedDirection("RIGHT"); end
        return nil;
    end

    view:HookScript("OnUpdate", function()
        if (resizeDirection) then return; end

        -- skip edge detection if another window is being dragged or resized
        if (isInteracting and not view.amResizing) then
            UpdateResizeCursor(nil);
            return;
        end
        local dir = GetResizeDirection();
        UpdateResizeCursor(dir);
    end);

    view:HookScript("OnMouseDown", function(_, button)
        if (button == "LeftButton") then
            -- skip if another window is already being dragged or resized
            if (isInteracting) then return; end
            local dir = GetResizeDirection();
            if (dir) then
                resizeDirection = dir;
                view.amResizing = true;
                isInteracting = true;
                view:StopMovingOrSizing();
                view:StartSizing(dir);
            end
        end
    end);

    view:HookScript("OnMouseUp", function(_, button)
        if (resizeDirection) then
            view:StopMovingOrSizing();
            resizeDirection = nil;
            view.amResizing = false;
            isInteracting = false;
            local dir = GetResizeDirection();
            UpdateResizeCursor(dir);
            service:StorePosition(view);
            service:StoreSize(view);
        end
    end);

    view:HookScript("OnLeave", function()
        if (not resizeDirection) then
            UpdateResizeCursor(nil);
        end
    end);

    -- a hidden view gets neither OnUpdate nor OnLeave, so the cursor frame
    -- (child of UIParent) would stay at the mouse; end a running resize too
    view:HookScript("OnHide", function()
        if (resizeDirection) then
            view:StopMovingOrSizing();
            resizeDirection = nil;
            view.amResizing = false;
            isInteracting = false;
            service:StorePosition(view);
            service:StoreSize(view);
        end
        UpdateResizeCursor(nil);
    end);
end

--- Bind a simple tooltip to a frame.
-- Shows tooltip on enter, hides on leave. Uses HookScript so existing handlers are preserved.
-- @param frame The frame to bind the tooltip to.
-- @param text Tooltip text string or function returning text (nil to suppress tooltip).
-- @param anchorPoint Optional anchor point (default "ANCHOR_BOTTOM").
function UiService:BindTooltip(frame, text, anchorPoint)
    local anchor = anchorPoint or "ANCHOR_BOTTOM";
    frame:HookScript("OnEnter", function(button)
        local tooltipText = type(text) == "function" and text() or text;
        if (type(tooltipText) ~= "string" or tooltipText == "") then return; end
        GameTooltip:SetOwner(button, anchor);
        GameTooltip:SetText(tooltipText);
        GameTooltip:Show();
    end);
    frame:HookScript("OnLeave", function()
        GameTooltip:Hide();
    end);
end

