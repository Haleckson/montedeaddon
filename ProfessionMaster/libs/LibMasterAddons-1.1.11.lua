--- Generate a random alphanumeric string (frame names, ids).
-- @param length Length of the string.
-- @return Random string.
function AddonContainer:GenerateString(length)
    local id = {};
    for i = 1, length do
        table.insert(id, idCharset[math.random(1, #idCharset)]);
