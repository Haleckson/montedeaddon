--- Quests an NPC gives that the character you play can take.
function Ref:QuestsGivenBy(npcID)
    return fitting(self, npcID and self:Index().givers[npcID])
end

--- Quests a creature is needed for (to kill, loot or talk to).
function Ref:QuestsTargeting(npcID)
    return fitting(self, npcID and self.targets[npcID])
end

--- Quests that start from an item this creature drops.
function Ref:QuestsFromLoot(npcID)
    return fitting(self, npcID and self.lootStarts[npcID])
end

function Ref:Npc(npcID)
    return npcID and self.npcs[npcID] or nil
end

--- A creature's role letters: r rare, w world boss, b dungeon boss,
--- v vendor, t trainer, f flight master.
function Ref:Is(npcID, letter)
    local npc = npcID and self.npcs[npcID]
    return npc ~= nil and npc.k ~= nil and npc.k:find(letter, 1, true) ~= nil
end

--- Where an item comes from: { droppers, sellers (NPC IDs), rewardOf,
--- neededFor (quest IDs you can take), starts (quest ID) }.
function Ref:ItemSources(itemID)
    local index = self:Index()
    local starts = self.starters[itemID]
    return {
        droppers = index.droppers[itemID] or EMPTY,
        sellers = index.sellers[itemID] or EMPTY,
        rewardOf = fitting(self, index.rewards[itemID]),
        neededFor = fitting(self, self.questItems[itemID]),
        starts = starts and self:Fits(self.quests[starts]) and starts or nil,
    }
end

--- A creature's name as far as it is known right now, and where it comes
--- from; nil when nobody can name it yet. The game is not asked.
---   "client"     the game's own name, in the player's language (asked earlier this session)
---   "learned"    seen in play by one of your characters or a guild member
---   "reference"  the English name the addon ships (quest givers, new rares)
function Ref:KnownNpcName(npcID)
    if not npcID then return nil end
    local name = self.names[npcID]
    if name then return name, "client" end
    local lore = FC.QuestLore and FC.QuestLore:GetNpc(npcID)
    if lore and lore.n then return lore.n, "learned" end
    name = self.shippedNames[npcID] or self.npcNames[npcID]
    if name then return name, "reference" end
    return nil
end

--- A creature's name: learned, else from the game (the first call may only
--- ask the server), else the English name the data ships for it, else nil.
--- An English client is not asked for a name the data ships: it is the same.
function Ref:NpcName(npcID)
    if not npcID then return nil end
    local known, source = self:KnownNpcName(npcID)
    if known and (source ~= "reference" or FC.Locale.client == "enUS") then return known end
    local name = Compat.GetCreatureName(npcID)
    if name then self.names[npcID] = name end
    return name or known
end

--- Has the game asked for a creature's name in the background: a few
--- creatures per round, again a little later when the game had to fetch it
--- first, and let go for the session when it never answers. NPC_NAMES_CHANGED
--- tells when names arrived. Returns whether the creature was queued.
function Ref:WantNpcName(npcID)
    if type(npcID) ~= "number" or self.names[npcID] or self.nameGivenUp[npcID] or self.nameWanted[npcID] then return false end
    self.nameWanted[npcID] = { tries = 0, at = 0 }
    self.nameQueue[#self.nameQueue + 1] = npcID
    if not self.nameTicker then
        self.nameTicker = C_Timer.NewTicker(NAME_TICK, function() FC:SafeCall("Reference:NamePump", self.NamePump, self) end)
    end
    return true
end

function Ref:NamePump()
    local now = GetTime()
    local later, asked, arrived = {}, 0, false
    for _, npcID in ipairs(self.nameQueue) do
        local state = self.nameWanted[npcID]
        if state then
            if asked >= NAME_BATCH or state.at > now then
                later[#later + 1] = npcID
            else
                asked = asked + 1
                local name = Compat.GetCreatureName(npcID)
                if name then
                    self.names[npcID] = name
                    self.nameWanted[npcID] = nil
                    arrived = true
                else
                    state.tries = state.tries + 1
                    local wait = NAME_RETRY[state.tries]
                    if wait then
                        state.at = now + wait
                        later[#later + 1] = npcID
                    else
                        self.nameWanted[npcID] = nil
                        self.nameGivenUp[npcID] = true
                    end
                end
            end
        end
    end
    self.nameQueue = later
    if arrived then U.Debounce("npc-names-changed", 0.2, function() FC.Bus:Emit("NPC_NAMES_CHANGED") end) end
    if #later == 0 and self.nameTicker then
        self.nameTicker:Cancel()
        self.nameTicker = nil
    end
end

--- For lists: the best name known for a creature right now (see
--- KnownNpcName), without waiting. When the game could do better (nobody
--- can name the creature, or only in English on a client in another
--- language) it is asked in the background. A page calls this for the rows
--- it draws, never for a whole list.
function Ref:DisplayNpcName(npcID)
    local name, source = self:KnownNpcName(npcID)
    if npcID and (not name or (source == "reference" and FC.Locale.client ~= "enUS")) then self:WantNpcName(npcID) end
    return name, source
end

--- An object's name: the main data's, else the English one shipped for the
--- objects that give quests (the game does not name an object by its ID).
function Ref:ObjectName(objectID)
    local object = objectID and self.objects[objectID]
    return (object and object.n) or (objectID and self.objectNames[objectID]) or nil
end

------------------------------------------------------------------------
-- Quests by ID (the completed quests of a character are only IDs)
------------------------------------------------------------------------

--- The English title and the level the data ships for a quest (nil, nil for
--- a quest it does not know). The client's own title is in the player's
--- language and wins whenever it has one (QuestLore:KnownTitle).
function Ref:QuestTitle(questID)
    local packed = questID and self.titles[questID]
    if type(packed) ~= "string" then return nil, nil end
    local level, title = packed:match("^(%d+)|(.+)$")
    if not title then return nil, nil end
    level = tonumber(level)
    return title, (level and level > 0) and level or nil
end

--- Where a quest belongs: its zone map (nil for class, profession and event
--- quests) and the zone's name, for the character you play.
function Ref:QuestZone(questID)
    local q = questID and self.quests[questID]
    if not q then return nil, nil end
    local mapID = q.m
    if q.am and self:Me().faction == 2 then mapID = q.am end
    if mapID then return mapID, Compat.GetMapName(mapID) end
    return nil, q.za and self.areaNames[q.za] or nil
end

-- The creature that gives a quest to the character you play. A quest with a
-- second place for the Alliance (am) lists its Alliance giver second; of
-- several givers, one of the other faction is passed over.
local function giverOf(self, q)
    local list = q and q.g
    if not list or not list[1] then return nil end
    if not list[2] then return list[1] end
    local faction = self:Me().faction
    if q.am and faction == 2 then return list[2] end
    for _, npcID in ipairs(list) do
        local npc = self.npcs[npcID]
        if not (npc and npc.f and faction and npc.f ~= faction) then return npcID end
    end
    return list[1]
end

--- Who gives a quest: the giver's NPC ID and name as far as it is known
--- (nil when the data names none, or the giver is an object or an item).
--- The game is not asked for the name (see DisplayNpcName).
function Ref:QuestGiver(questID)
    local npcID = giverOf(self, questID and self.quests[questID])
    if not npcID then return nil, nil end
    return npcID, (self:KnownNpcName(npcID))
end

--- Where a quest starts, as far as the data says:
--- { kind = "npc" | "object" | "item", id, name (nil while nobody can name
---   it), item (an item that starts it too, or instead), m, x, y (the place,
---   0-1; nil when the data has none) },
--- or nil for a quest it names no start for. The game is not asked.
function Ref:QuestStart(questID)
    local q = questID and self.quests[questID]
    if not q then return nil end
    local npcID = giverOf(self, q)
    local itemID = q.gi and q.gi[1]
    local start
    if npcID then
        start = { kind = "npc", id = npcID, name = (self:KnownNpcName(npcID)) }
    elseif q.go and q.go[1] then
        start = { kind = "object", id = q.go[1], name = self:ObjectName(q.go[1]) }
    elseif itemID then
        start = { kind = "item", id = itemID }
    else
        return nil
    end
    start.item = itemID
    start.m, start.x, start.y = self:QuestPlace(questID)
    if not start.m and start.kind == "npc" then start.m, start.x, start.y = self:Place(self.npcs[start.id]) end
    if not start.m and start.kind == "object" then start.m, start.x, start.y = self:Place(self.objects[start.id]) end
    local places = self.giverPlaces[start.kind]
    if not start.m and type(places) == "table" then start.m, start.x, start.y = self:Place(places[start.id]) end
    return start
end
