--[[
  Forever Companion - Data/Reference.lua
  The WoW Forever reference data in Data/Reference/*.lua, generated by
  tools/import_att.lua from the database of AllTheThings (MIT License, see
  THIRD_PARTY_NOTICES.md): every quest with its givers, faction, classes,
  races, level and prerequisites; what each creature drops and which
  quests need it; treasure, flight paths, dungeons and what each zone holds.

  Data/Reference/Wowhead.lua (generated by Tools/import_wowhead.py from the
  listings of Wowhead's WoW Forever database) adds what that data lacks: an
  English title and the level of every quest, used until the client names a
  quest itself, and the quests and rares WoW Forever added that AllTheThings
  does not list yet. Those come without a quest giver or a position; where
  a quest starts is learned in play (QuestLore). It also carries the English
  names of the creatures and objects that give quests (from Wowhead's
  tooltip service, Tools/fetch_wowhead_names.py): the game only tells a
  creature's name when it is asked for one creature at a time, and never an
  object's, so a list can name a quest giver at once and the game's own
  name, in the player's language, takes over when it arrives.

  Data/Reference/Starts.lua (generated by Tools/import_att_starts.py from the
  newer AllTheThings data) names who gives a quest, and where, for quests the
  files above have no start for: mostly the quests WoW Forever added.

  It is read-only. What your characters and your guild learn (QuestLore,
  the journal) comes on top of it, and lists are filtered to what the
  character you play can do: its faction, class and race.
]]

local _, FC = ...

local Ref = FC:NewModule("Reference")

local Compat = FC.Compat
local U = FC.Utils

local EMPTY = {}

local NAME_TICK = 0.25              -- seconds between two rounds of names asked from the game
local NAME_BATCH = 8                -- creatures asked for per round
local NAME_RETRY = { 0.5, 1.5, 4 }  -- seconds before a creature is asked for again; then it is let go for the session

function Ref:OnInitialize()
    local R = FC.ReferenceData or {}
    for _, key in ipairs({ "quests", "starters", "questItems", "npcs", "targets", "lootStarts", "zones", "objects", "flightPaths", "instances" }) do
        self[key] = type(R[key]) == "table" and R[key] or {}
    end
    self.titles = type(R.questTitles) == "table" and R.questTitles or {}
    self.areaNames = type(R.areaNames) == "table" and R.areaNames or {}
    -- English names of the creatures and objects that give quests, and where
    -- the givers stand that the main data has no place for
    self.npcNames = type(R.npcNames) == "table" and R.npcNames or {}
    self.objectNames = type(R.objectNames) == "table" and R.objectNames or {}
    self.giverPlaces = type(R.giverPlaces) == "table" and R.giverPlaces or {}
    self.index, self.me, self.names, self.shippedNames = nil, nil, {}, {}
    self.nameQueue, self.nameWanted, self.nameGivenUp = {}, {}, {}
    self:MergeExtras(R)
end

--- Joins what Data/Reference/Wowhead.lua adds: quests and rares the main
--- data does not have. A quest nobody saw start (nz) stays out of its
--- zone's list, so a zone's total only counts quests known to be offered.
function Ref:MergeExtras(R)
    if R.fcExtrasMerged then return end
    R.fcExtrasMerged = true
    local function zoneList(mapID, key)
        local zone = self.zones[mapID]
        if not zone then
            zone = {}
            self.zones[mapID] = zone
        end
        zone[key] = zone[key] or {}
        return zone[key]
    end
    -- Starts.lua: who gives a quest and where, for a quest no other file names a
    -- start for. Returns whether the quest took it.
    local starts = type(R.questStarts) == "table" and R.questStarts or EMPTY
    local function takeStart(questID, q)
        local start = starts[questID]
        if type(start) ~= "table" or q.g or q.go or q.gi then return false end
        q.g, q.go = start.g, start.go
        q.f = q.f or start.f
        -- the place comes with its map; a quest that has a place keeps it
        if start.m and start.x and not q.x then q.m, q.x, q.y = start.m, start.x, start.y end
        return true
    end
    for questID, q in pairs(type(R.extraQuests) == "table" and R.extraQuests or EMPTY) do
        if self.quests[questID] == nil and type(q) == "table" then
            self.quests[questID] = q
            -- a quest the newer data names a giver for is offered: it belongs to its zone
            if takeStart(questID, q) then q.nz = nil end
            if q.m and not q.nz then
                local list = zoneList(q.m, "q")
                list[#list + 1] = questID
            end
        end
    end
    for questID in pairs(starts) do
        local q = self.quests[questID]
        if type(q) == "table" then takeStart(questID, q) end -- the main data's quests without a start
    end
    for npcID, rare in pairs(type(R.extraRares) == "table" and R.extraRares or EMPTY) do
        if self.npcs[npcID] == nil and type(rare) == "table" and rare.m then
            self.npcs[npcID] = { k = "r", m = rare.m }
            self.shippedNames[npcID] = rare.n
            local list = zoneList(rare.m, "r")
            list[#list + 1] = npcID
        end
    end
end

function Ref:OnEnable()
    FC.Events:Register("PLAYER_ENTERING_WORLD", self, function() self.me = nil end)
end

function Ref:Available()
    return next(self.quests) ~= nil
end

------------------------------------------------------------------------
-- The character you play
------------------------------------------------------------------------

--- faction 1 Horde / 2 Alliance, class ID, race ID (nil when unknown).
function Ref:Me()
    if not self.me then
        local faction = Compat.SafeCall(_G.UnitFactionGroup, "player")
        local _, _, classID = Compat.SafeCall(_G.UnitClass, "player")
        local _, _, raceID = Compat.SafeCall(_G.UnitRace, "player")
        self.me = {
            faction = faction == "Horde" and 1 or (faction == "Alliance" and 2 or nil),
            class = type(classID) == "number" and classID or nil,
            race = type(raceID) == "number" and raceID or nil,
        }
    end
    return self.me
end

local function contains(list, value)
    for _, v in ipairs(list) do
        if v == value then return true end
    end
    return false
end

--- Whether the character you play can take a quest: faction, class, race.
function Ref:Fits(q)
    if type(q) ~= "table" then return false end
    local me = self:Me()
    if q.f and me.faction and q.f ~= me.faction then return false end
    if q.c and me.class and not contains(q.c, me.class) then return false end
    if q.rc and me.race and not contains(q.rc, me.race) then return false end
    return true
end

--- Where a quest is picked up, for the character you play: map, x, y (0-1).
function Ref:QuestPlace(questID)
    local q = self.quests[questID]
    if not q then return nil end
    if q.am and self:Me().faction == 2 then return q.am, q.ax / 100, q.ay / 100 end
    if q.m and q.x then return q.m, q.x / 100, q.y / 100 end
    return nil
end

--- Where a creature or object stands: map, x, y (0-1).
function Ref:Place(entry)
    if type(entry) == "table" and entry.m and entry.x then return entry.m, entry.x / 100, entry.y / 100 end
    return nil
end

------------------------------------------------------------------------
-- Indexes (built on first use)
------------------------------------------------------------------------

local function push(map, key, value)
    local list = map[key]
    if not list then
        list = {}
        map[key] = list
    end
    list[#list + 1] = value
end

function Ref:Index()
    if self.index then return self.index end
    local index = { givers = {}, objectGivers = {}, rewards = {}, droppers = {}, sellers = {} }
    for questID, q in pairs(self.quests) do
        for _, npcID in ipairs(q.g or EMPTY) do push(index.givers, npcID, questID) end
        for _, objectID in ipairs(q.go or EMPTY) do push(index.objectGivers, objectID, questID) end
        for _, itemID in ipairs(q.rw or EMPTY) do push(index.rewards, itemID, questID) end
    end
    for npcID, npc in pairs(self.npcs) do
        local sells = npc.k and npc.k:find("v", 1, true)
        for _, itemID in ipairs(npc.d or EMPTY) do push(sells and index.sellers or index.droppers, itemID, npcID) end
    end
    self.index = index
    return index
end

local function fitting(self, list)
    local out = {}
    for _, questID in ipairs(list or EMPTY) do
        if self:Fits(self.quests[questID]) then out[#out + 1] = questID end
    end
    return out
end

